  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  pid INT UNSIGNED NOT NULL DEFAULT 0,
  login VARCHAR(30) NOT NULL,
  vnum INT(6) UNSIGNED NOT NULL DEFAULT 0,
  count INT UNSIGNED NOT NULL DEFAULT 0,
