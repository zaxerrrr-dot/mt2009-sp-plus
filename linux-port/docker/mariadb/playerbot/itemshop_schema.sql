-- Kola Losu z wheel_prizes, ktore zostaje tylko jako tabela). Jedno zrodlo dla sklepu
-- (itemshop/app/itemshop/kola/kola_lib.php) i okna F12 w grze (playerbot_wheel.h):
--   kola_wheel / kola_pool / kola_item - kola, pule nagrod, przypisanie id zrodla -> vnum
--                                        (blok SEED nizej, generowany, nadpisywany przy starcie);
--                                        expire_rel > 0: socket0 = teraz + expire_rel przy wydaniu
--                                        (przedmiot na czas rzeczywisty z innym czasem niz w proto)
--   kola_settings  - aktywne kolo (override z panelu, 0 = rotacja co 14 dni), rotacja, czas poziomu
--   kola_state     - stan konta: kolo, poziom, klucze, czas poziomu, ostatni uklad pol, token
--   kola_spin_log  - kazdy obrot (www i F12)
CREATE TABLE IF NOT EXISTS itemshop.kola_wheel (
  id INT NOT NULL PRIMARY KEY,
  name VARCHAR(64) NOT NULL,
  max_tier TINYINT NOT NULL DEFAULT 3,
  cost1 INT NOT NULL DEFAULT 0,
  cost2 INT NOT NULL DEFAULT 0,
  cost3 INT NOT NULL DEFAULT 0,
  ord TINYINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS itemshop.kola_pool (
  wheel_id INT NOT NULL,
  tier TINYINT NOT NULL,
  special TINYINT NOT NULL,
  ord SMALLINT NOT NULL,
  src_id VARCHAR(64) NOT NULL,
  count INT NOT NULL DEFAULT 1,
  weight INT NOT NULL,
  PRIMARY KEY (wheel_id, tier, special, ord)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS itemshop.kola_item (
  src_id VARCHAR(64) NOT NULL PRIMARY KEY,
  vnum INT UNSIGNED NOT NULL DEFAULT 0,
  count_mul INT NOT NULL DEFAULT 1,
  socket0 INT NOT NULL DEFAULT 0,
  socket1 INT NOT NULL DEFAULT 0,
  socket2 INT NOT NULL DEFAULT 0,
  expire_rel INT NOT NULL DEFAULT 0,
  icon_vnum INT UNSIGNED NOT NULL DEFAULT 0,
  status VARCHAR(12) NOT NULL DEFAULT 'ok',
  name VARCHAR(96) NOT NULL DEFAULT '',
  src_name VARCHAR(96) NOT NULL DEFAULT '',
  note VARCHAR(1024) NOT NULL DEFAULT '',
  src_icon TINYINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS itemshop.kola_settings (
  name VARCHAR(32) NOT NULL PRIMARY KEY,
  value VARCHAR(255) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

