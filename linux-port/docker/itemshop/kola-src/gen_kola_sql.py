#!/usr/bin/env python3
# MT2009_PLUS_KOLA_V1: writes the wheels' seed into mariadb/playerbot/itemshop_schema.sql
# (between the "-- MT2009_PLUS_KOLA_V1 SEED BEGIN/END" lines) from
#   app/itemshop/kola/kola.json  - the six wheels as the source has them: costs per tier,
#                                  the special/standard pools (source ids, counts, weights)
#   kola-src/przedmioty.json     - source id -> our vnum (status ok / inny_czas / zamiennik / brak)
# The game (playerbot_wheel.h) and the shop (kola/kola_lib.php) both read only the database,
# so a replacement changed in przedmioty.json reaches both after this script and a restart
# (playerbot-migrate applies itemshop_schema.sql at every start).
#   python3 linux-port/docker/itemshop/kola-src/gen_kola_sql.py
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
CFG = os.path.join(HERE, '..', 'app', 'itemshop', 'kola', 'kola.json')
MAP = os.path.join(HERE, 'przedmioty.json')
SQL = os.path.join(HERE, '..', '..', 'mariadb', 'playerbot', 'itemshop_schema.sql')
BEGIN = '-- MT2009_PLUS_KOLA_V1 SEED BEGIN'
END = '-- MT2009_PLUS_KOLA_V1 SEED END'


def q(s):
    return "'" + str(s).replace('\\', '\\\\').replace("'", "''") + "'"


def main():
    cfg = json.load(open(CFG, encoding='utf-8'))
    mapping = json.load(open(MAP, encoding='utf-8')) if os.path.exists(MAP) else {}
    out = [BEGIN,
           '-- Generated by linux-port/docker/itemshop/kola-src/gen_kola_sql.py - edit przedmioty.json /',
           '-- kola.json and run it again, not this block. Replaced every start: the repository decides.']
    order = cfg['rotation']['order']
    out.append('DELETE FROM itemshop.kola_wheel;')
    rows = []
    for n, wid in enumerate(order):
        w = cfg['wheels'][str(wid)]
        costs = [int(w['costs'].get(str(t), 0)) for t in (1, 2, 3)]
        tiers = max(int(t) for t in w['costs'])
        rows.append('(%d, %s, %d, %d, %d, %d, %d)' % (wid, q(w['name']), tiers, costs[0], costs[1], costs[2], n + 1))
    out.append('INSERT INTO itemshop.kola_wheel (id, name, max_tier, cost1, cost2, cost3, ord) VALUES\n  ' + ',\n  '.join(rows) + ';')
    out.append('DELETE FROM itemshop.kola_pool;')
    used = {}
    for wid in order:
        w = cfg['wheels'][str(wid)]
        rows = []
        for t in sorted(w['prizes'], key=int):
            for pool, special in (('special', 1), ('standard', 0)):
                for i, (src, count, weight) in enumerate(w['prizes'][t][pool]):
                    wx = int(round(float(weight) * 100))
                    assert abs(wx - float(weight) * 100) < 1e-6, (wid, t, src, weight)
                    rows.append('(%d, %d, %d, %d, %s, %d, %d)' % (wid, int(t), special, i + 1, q(src), int(count), wx))
                    used.setdefault(str(src), []).append(wid)
        out.append('INSERT INTO itemshop.kola_pool (wheel_id, tier, special, ord, src_id, count, weight) VALUES\n  ' + ',\n  '.join(rows) + ';')
    out.append('DELETE FROM itemshop.kola_item;')
    rows = []
    missing = []
    for src in sorted(used, key=lambda s: (not s.isdigit(), int(s) if s.isdigit() else 0, s)):
        m = mapping.get(src)
        srcname = (cfg['src_items'].get(src) or {}).get('name') or src
        if not m or not m.get('vnum'):
            missing.append(src)
            m = {'vnum': 0, 'status': 'brak', 'name': srcname, 'note': 'brak przypisania'}
        icon = 1 if (m.get('status') in ('ok', 'inny_czas') and src in cfg['src_items']) else 0
        rows.append('(%s, %d, %d, %d, %d, %d, %d, %d, %s, %s, %s, %s, %d)' % (
            q(src), int(m['vnum']), int(m.get('count_mul') or 1), int(m.get('socket0') or 0), int(m.get('socket1') or 0),
            int(m.get('socket2') or 0), int(m.get('expire_rel_sec') or 0), int(m.get('icon_vnum') or 0),
            q(m.get('status') or 'ok'), q(m.get('name') or srcname), q(srcname), q(m.get('note') or ''), icon))
    out.append('INSERT INTO itemshop.kola_item (src_id, vnum, count_mul, socket0, socket1, socket2, expire_rel, icon_vnum, status, name, src_name, note, src_icon) VALUES\n  '
               + ',\n  '.join(rows) + ';')
    out.append(END)
    block = '\n'.join(out) + '\n'
    text = open(SQL, encoding='utf-8').read()
    if BEGIN in text:
        a = text.index(BEGIN)
        b = text.index(END) + len(END) + 1
        text = text[:a] + block + text[b:]
    else:
        text = text.rstrip('\n') + '\n\n' + block
    open(SQL, 'w', encoding='utf-8').write(text)
    print('wheels %d, items %d, without vnum %d %s' % (len(order), len(used), len(missing), missing[:10]))


if __name__ == '__main__':
    main()
