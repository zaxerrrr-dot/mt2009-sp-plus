	// The maps a dungeon row is played on (Jaskinie Gnolli: its three levels).
	void GetPlayerBotDkDefMaps(int def, std::vector<long>& out)
	{
		out.clear();
		const TPlayerBotDgRunDef& d = PLAYERBOT_DGRUN_DEFS[def];
		out.push_back(d.lMap);
		if (d.bKind == DGRUN_KIND_GNOLLE)
		{
			out.push_back(d.lMap + 1);
			out.push_back(d.lMap + 2);
		}
	}

	// The lowest level a bot goes into the row with (the bots' own floors: the YDG rows' 110 / the temple's 120, the panel's
	// level for the rest).
	int GetPlayerBotDkDefMinLevel(int def)
	{
		if (def < 0 || def >= PLAYERBOT_DGRUN_DEF_COUNT)
			return 0;
		const TPlayerBotDgRunDef& d = PLAYERBOT_DGRUN_DEFS[def];
		if (d.bKind == DGRUN_KIND_YDG)
			return GetPlayerBotYdgDefMinLevel(def);
		if (d.bKind == DGRUN_KIND_GNOLLE)
			return std::max(PLAYERBOT_GNOLLE_MIN_LEVEL, (int)gPlayerMaxLevel);
		if (d.bKind == DGRUN_KIND_MELEY)
			return PLAYERBOT_MELEY_MIN_LEVEL;
		const mt2009_dpanel::Def* panel = mt2009_dpanel::FindKey(d.szKey);
		return panel ? std::max(panel->lvMin, (int)PLAYERBOT_DGRUN_MIN_LEVEL) : (int)PLAYERBOT_DGRUN_MIN_LEVEL;
	}

