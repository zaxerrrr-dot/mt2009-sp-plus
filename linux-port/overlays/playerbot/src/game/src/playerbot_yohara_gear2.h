	// The census: the bots wearing level-96+ helmets, armours and weapons, by level band, and their average plus.
	void LogPlayerBotGear2Census(DWORD dwNow, bool force)
	{
		if (!force && s_kPlayerBotGear2Stats.dwLastCensus != 0 && dwNow - s_kPlayerBotGear2Stats.dwLastCensus < PLAYERBOT_GEAR2_CENSUS_MS)
			return;
		s_kPlayerBotGear2Stats.dwLastCensus = dwNow;
		// [slot][band] - bands: 96-99, 100-104, 105-109, 110-119, 120+
		int count[3][5] = { { 0 } }, plus[3][5] = { { 0 } };
		int planned = 0, ready = 0, busy = 0;
		static const BYTE s_aCells[3] = { WEAR_HEAD, WEAR_BODY, WEAR_WEAPON };
		for (TPlayerBotAIStateMap::const_iterator st = s_mapPlayerBotAIStates.begin(); st != s_mapPlayerBotAIStates.end(); ++st)
		{
			LPCHARACTER ch = CHARACTER_MANAGER::instance().FindByPID(st->first);
			if (!ch || !ch->IsItemLoaded())
				continue;
			for (int c = 0; c < 3; ++c)
			{
				LPITEM worn = ch->GetWear(s_aCells[c]);
				const int lv = worn ? GetPlayerBotGear2ProtoLevel(worn->GetProto()) : 0;
				if (lv < 96)
					continue;
				const int band = lv >= 120 ? 4 : lv >= 110 ? 3 : lv >= 105 ? 2 : lv >= 100 ? 1 : 0;
				++count[c][band];
				plus[c][band] += (int)worn->GetRefineLevel();
			}
			std::map<DWORD, TPlayerBotGear2Bot>::const_iterator b = s_mapPlayerBotGear2.find(st->first);
			if (b == s_mapPlayerBotGear2.end())
				continue;
			planned += b->second.targets.empty() ? 0 : 1;
			busy += b->second.bPhase != 0 ? 1 : 0;
			for (size_t i = 0; i < b->second.targets.size(); ++i)
				if (b->second.targets[i].bReady)
				{
					++ready;
					break;
				}
		}
		char line[3][160];
		static const char* const s_aNames[3] = { "head", "body", "weapon" };
		for (int c = 0; c < 3; ++c)
		{
			int n = 0;
			n += snprintf(line[c] + n, sizeof(line[c]) - n, "%s", s_aNames[c]);
			static const char* const s_aBands[5] = { "96", "100", "105", "110", "120" };
			for (int k = 0; k < 5 && n < (int)sizeof(line[c]); ++k)
				n += snprintf(line[c] + n, sizeof(line[c]) - n, " %s:%d(+%d.%d)", s_aBands[k], count[c][k],
						count[c][k] ? plus[c][k] / count[c][k] : 0, count[c][k] ? (plus[c][k] * 10 / count[c][k]) % 10 : 0);
		}
		const TPlayerBotGear2Stats& s = s_kPlayerBotGear2Stats;
		sys_log(0, "PLAYERBOT_GEAR2: census planned=%d ready=%d at_npc=%d crafted jaharr=%u/%u kawuco=%u/%u angmur=%u/%u "
				"seonpyeong=%u/%u (made/failed) bought=%u bought_yang=%lld spent_yang=%lld trips=%u cape_trips=%u | %s | %s | %s",
				planned, ready, busy, s.crafted[0], s.failed[0], s.crafted[1], s.failed[1], s.crafted[2], s.failed[2], s.crafted[3],
				s.failed[3], s.bought, s.boughtYang, s.spentYang, s.trips, s.capeTrips, line[0], line[1], line[2]);
	}

	// The operator's test file (the core's directory): "plan [n]", "mats <n>", "status".
	void RunPlayerBotGear2TestFile(DWORD dwNow)
	{
		if (dwNow - s_kPlayerBotGear2Stats.dwLastTestLook < 10000)
			return;
		s_kPlayerBotGear2Stats.dwLastTestLook = dwNow;
		FILE* fp = fopen(PLAYERBOT_GEAR2_TEST_FILE, "r");
		if (!fp)
			return;
		char buf[128];
		std::vector<std::string> lines;
		while (fgets(buf, sizeof(buf), fp))
			lines.push_back(buf);
		fclose(fp);
		char done[128];
		snprintf(done, sizeof(done), "%s.done", PLAYERBOT_GEAR2_TEST_FILE);
		rename(PLAYERBOT_GEAR2_TEST_FILE, done);
		for (size_t l = 0; l < lines.size(); ++l)
		{
			char cmd[32] = "", arg[32] = "";
			if (sscanf(lines[l].c_str(), "%31s %31s", cmd, arg) < 1)
				continue;
			if (!strcmp(cmd, "status"))
			{
				LogPlayerBotGear2Census(dwNow, true);
				continue;
			}
			const int n = !strcmp(arg, "all") ? 100000 : (*arg ? atoi(arg) : 20);
			int did = 0;
			for (TPlayerBotAIStateMap::const_iterator st = s_mapPlayerBotAIStates.begin();
					st != s_mapPlayerBotAIStates.end() && did < n; ++st)
			{
				LPCHARACTER ch = CHARACTER_MANAGER::instance().FindByPID(st->first);
				if (!IsPlayerBotGear2Bot(ch))
					continue;
				TPlayerBotGear2Bot& b = GetPlayerBotGear2(ch, dwNow);
				if (b.targets.empty())
					continue;
				++did;
				for (size_t i = 0; i < b.targets.size(); ++i)
				{
					TPlayerBotGear2Target& t = b.targets[i];
					if (!strcmp(cmd, "mats") && i == 0)
					{
						for (int m = 0; m < 5; ++m)
						{
							const int lack = t.adwMat[m] ? t.aiCount[m] - (int)ch->CountSpecifyItem(t.adwMat[m]) : 0;
							if (lack > 0)
								ch->AutoGiveItem(t.adwMat[m], (ITEM_COUNT)lack, -1, false);
						}
						if (GetPlayerBotGear2Spare(ch) < t.llGold)
							PlayerBotChangeGold(ch, t.llGold - GetPlayerBotGear2Spare(ch));
						b.dwNextCheck = 0;
					}
					sys_log(0, "PLAYERBOT_GEAR2: test %s pid=%u name=%s level=%u map=%ld slot=%u npc=%s input=%u reward=%u chance=%d "
							"yang=%lld piece_ready=%d mats=%d/%d gold=%lld",
							cmd, ch->GetPlayerID(), ch->GetName(), (unsigned int)ch->GetLevel(), ch->GetMapIndex(),
							(unsigned int)t.bWearCell, PLAYERBOT_GEAR2_NPC_NAMES[t.bNpc], t.dwInput, t.dwReward, t.iPercent, t.llGold,
							t.bPieceReady ? 1 : 0, GetPlayerBotGear2Coverage(ch, t), 1000, (long long)ch->GetGold());
				}
			}
			sys_log(0, "PLAYERBOT_GEAR2: test %s asked=%d done=%d", cmd, n, did);
		}
	}

	// The AI's tick, beside the workshop: true while the errand owns the bot.
	bool ManagePlayerBotGear2(LPCHARACTER ch, TPlayerBotAIState& state, DWORD dwNow)
	{
		RunPlayerBotGear2TestFile(dwNow);
		LogPlayerBotGear2Census(dwNow, false);
		if (!IsPlayerBotGear2Bot(ch) || ch->IsDead())
			return false;
		const DWORD pid = ch->GetPlayerID();
		TPlayerBotGear2Bot& b = GetPlayerBotGear2(ch, dwNow);
		const bool otherErrand = state.bVisitingShop || state.bVisitingBiologist || state.bVisitingHerbalist ||
				state.bVisitingStable || state.bVisitingAlchemist || state.bVisitingUriel || state.bFishingSession ||
				state.bMarketTrip || state.bVisitingYonah;
		if (otherErrand || IsPlayerBotGear2Off() || (ch->GetParty() && IsPlayerBotHumanLedParty(ch->GetParty())) ||
				IsPlayerBotHeldForCompany(ch) || ch->GetMyShop() != NULL || ch->GetExchange() || IsPlayerBotArezzoHeldHere(ch) ||
				IsPlayerBotOnDungeonRun(pid))
		{
			if (b.bPhase != 0)
				EndPlayerBotGear2Visit(ch, state, b, dwNow, "interrupted");
			return false;
		}
		// a trade trip's bot at home: no wait for the clock
		if (b.bPhase == 0 && IsPlayerBotSungmaTradeVisitor(pid) && b.dwNextCheck != 0 && (int)(b.dwNextCheck - dwNow) > 60000)
			b.dwNextCheck = dwNow;
		if (b.bPhase == 0)
		{
			if ((int)(dwNow - b.dwNextCheck) < 0)
				return false;
			b.dwNextCheck = dwNow + number(PLAYERBOT_GEAR2_CHECK_MIN_MS, PLAYERBOT_GEAR2_CHECK_MAX_MS);
			const TPlayerBotGear2Target* t = NULL;
			int spot = -1;
			bool travel = false;
			for (size_t i = 0; i < b.targets.size() && spot < 0; ++i)
			{
				if (!b.targets[i].bReady)
					continue;
				spot = ChoosePlayerBotGear2Spot(ch, b.targets[i].bNpc, travel);
				if (spot >= 0)
					t = &b.targets[i];
			}
			if (!t)
			{
				const TPlayerBotGear2Target* waiting = GetPlayerBotGear2ReadyTarget(ch, b, -1);
				if (waiting && (int)(dwNow - b.dwNextWaitLog) >= 0)
				{
					b.dwNextWaitLog = dwNow + PLAYERBOT_GEAR2_WAIT_LOG_MS;
					sys_log(0, "PLAYERBOT_GEAR2: waiting pid=%u name=%s level=%u map=%ld npc=%s input=%u reward=%u why=no_way_from_here",
							pid, ch->GetName(), (unsigned int)ch->GetLevel(), ch->GetMapIndex(), PLAYERBOT_GEAR2_NPC_NAMES[waiting->bNpc],
							waiting->dwInput, waiting->dwReward);
				}
				return false;
			}
			const TPlayerBotGear2Spot& sp = PLAYERBOT_GEAR2_SPOTS[spot];
			// Not from a fight (nor, for a trip, with what its town visit has to sort out first): the next look, then.
			if (ch->GetVictim() != NULL || state.dwTargetVID != 0 || state.bTacticalRetreat || (travel && BlocksPlayerBotTravel(ch)))
			{
				b.dwNextCheck = dwNow + number(20000, 60000);
				return false;
			}
			if (travel)
			{
				SetPlayerBotAction(state, BOT_ACTION_TRAVEL, dwNow);
				if (!TransitionPlayerBotMap(ch, state, sp.lMap, sp.lX, sp.lY, dwNow, "gear2_craft"))
				{
					PlayerBotLogThrottled("gear2_travel", dwNow, "PLAYERBOT_GEAR2: no way pid=%u name=%s from=%ld to=%ld npc=%s",
							pid, ch->GetName(), ch->GetMapIndex(), sp.lMap, PLAYERBOT_GEAR2_NPC_NAMES[t->bNpc]);
					return false;
				}
				++s_kPlayerBotGear2Stats.trips;
				if (!IsPlayerBotMapHostedHere(sp.lMap))
					++s_kPlayerBotGear2Stats.capeTrips;
				sys_log(0, "PLAYERBOT_GEAR2: going pid=%u name=%s level=%u from=%ld to=%ld npc=%s input=%u reward=%u",
						pid, ch->GetName(), (unsigned int)ch->GetLevel(), ch->GetMapIndex(), sp.lMap,
						PLAYERBOT_GEAR2_NPC_NAMES[t->bNpc], t->dwInput, t->dwReward);
				b.dwNextCheck = 0;	// straight to the NPC once it stands on the map
				return true;
			}
			b.bPhase = 1;
			b.bNpc = t->bNpc;
			b.iSpot = spot;
			b.iCrafts = 0;
			b.dwVisitStart = dwNow;
			b.dwNextAction = 0;
			state.dwTargetVID = 0;
			ch->SetVictim(NULL);
			ch->Stop();
			ClearPlayerBotRoute(state, true);
			sys_log(0, "PLAYERBOT_GEAR2: going pid=%u name=%s level=%u map=%ld npc=%s input=%u reward=%u gold=%lld",
					pid, ch->GetName(), (unsigned int)ch->GetLevel(), ch->GetMapIndex(), PLAYERBOT_GEAR2_NPC_NAMES[t->bNpc],
					t->dwInput, t->dwReward, (long long)ch->GetGold());
		}
		// At the NPC's map: the walk, then the crafts.
		if (b.iSpot < 0 || PLAYERBOT_GEAR2_SPOTS[b.iSpot].lMap != ch->GetMapIndex())
		{
			EndPlayerBotGear2Visit(ch, state, b, dwNow, "left_map");
			return false;
		}
		if (dwNow - b.dwVisitStart > PLAYERBOT_GEAR2_VISIT_MS)
		{
			EndPlayerBotGear2Visit(ch, state, b, dwNow, "timeout");
			return false;
		}
		SetPlayerBotAction(state, BOT_ACTION_SHOP, dwNow);
		state.dwTargetVID = 0;
		ch->SetVictim(NULL);
		const TPlayerBotGear2Spot& sp = PLAYERBOT_GEAR2_SPOTS[b.iSpot];
		long ax = 0, ay = 0;
		GetPlayerBotNpcApproach(pid, sp.lX, sp.lY, 0x47524b32U, ax, ay);
		if (DISTANCE_APPROX(ch->GetX() - ax, ch->GetY() - ay) > PLAYERBOT_GEAR2_REACH)
		{
			if (!MovePlayerBot(ch, ax, ay, dwNow, 20, true, true, false, true) && state.bStuckCounter >= 6)
			{
				sys_err("PLAYERBOT_GEAR2: route failed pid=%u name=%s map=%ld from=(%ld,%ld) to=(%ld,%ld)", pid, ch->GetName(),
						ch->GetMapIndex(), ch->GetX(), ch->GetY(), ax, ay);
				EndPlayerBotGear2Visit(ch, state, b, dwNow, "route_failed");
				return false;
			}
			return true;
		}
		ch->Stop();
		ch->SetPosition(POS_STANDING);
		if (b.dwNextAction == 0)
		{
			b.dwNextAction = dwNow + number(3000, 7000);
			return true;
		}
		if ((int)(dwNow - b.dwNextAction) < 0)
			return true;
		b.dwPlanAt = 0;	// what it wears may have changed - read the targets again
		TPlayerBotGear2Bot& fresh = GetPlayerBotGear2(ch, dwNow);
		const TPlayerBotGear2Target* t = b.iCrafts < PLAYERBOT_GEAR2_VISIT_CRAFTS ? GetPlayerBotGear2ReadyTarget(ch, fresh, b.bNpc) : NULL;
		if (!t)
		{
			EndPlayerBotGear2Visit(ch, state, b, dwNow, "done");
			return false;
		}
		const TPlayerBotGear2Target work = *t;
		const bool did = work.bNpc == PLAYERBOT_GEAR2_NPC_SEONPYEONG ? UpgradePlayerBotGear2Elite(ch, state, work)
				: CraftPlayerBotGear2Recipe(ch, state, work, dwNow);
		if (!did)
		{
			EndPlayerBotGear2Visit(ch, state, b, dwNow, "refused");
			return false;
		}
		++b.iCrafts;
		b.dwPlanAt = 0;
		b.dwNextAction = dwNow + number(2500, 5000);
		return true;
	}
