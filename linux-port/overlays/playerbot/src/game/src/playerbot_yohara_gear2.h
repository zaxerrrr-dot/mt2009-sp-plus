	// The spot the bot goes to for this NPC: on its map, else one it may travel to (-1: none from here).
	int ChoosePlayerBotGear2Spot(LPCHARACTER ch, int npc, bool& travel)
	{
		travel = false;
		const long map = ch->GetMapIndex();
		const int here = FindPlayerBotGear2SpotOn(npc, map);
		if (here >= 0)
			return here;
		// A Sung Ma bot moves only on its trade trip (Jaharr, Seon-Pyeong at home); Angmur where it stands.
		if (IsPlayerBotSungmaResidentPID(ch->GetPlayerID()))
			return -1;
		if (FindPlayerBotYoharaResident(ch->GetPlayerID()) && !IsPlayerBotSungmaTradeVisitor(ch->GetPlayerID()))
			return -1;
		switch (npc)
		{
			case PLAYERBOT_GEAR2_NPC_JAHARR:
			{
				long home = 0, x = 0, y = 0;
				if (!GetPlayerBotVillageReturn(ch, playerbot_empire_rules::MAP_ROLE_M1, home, x, y) || !IsPlayerBotMapHostedHere(home))
					return -1;
				travel = true;
				return FindPlayerBotGear2SpotOn(npc, home);
			}
			case PLAYERBOT_GEAR2_NPC_SEONPYEONG:
				if (!IsPlayerBotMapHostedHere(PLAYERBOT_GEAR2_MAP_ORC_VALLEY))
					return -1;
				travel = true;
				return FindPlayerBotGear2SpotOn(npc, PLAYERBOT_GEAR2_MAP_ORC_VALLEY);
			case PLAYERBOT_GEAR2_NPC_KAWUCO:
			case PLAYERBOT_GEAR2_NPC_ANGMUR:
				if (!IsPlayerBotMapHostedHere(PLAYERBOT_GEAR2_MAP_CAPE) &&
						(!IsPlayerBotGear2CapeOn() || !IsPlayerBotYoharaOn() || !IsPlayerBotYoharaHomeCore(ch) ||
						 !IsPlayerBotYoharaEligible(ch) || IsPlayerBotSungmaTradeVisitor(ch->GetPlayerID())))
					return -1;
				travel = true;
				return FindPlayerBotGear2SpotOn(npc, PLAYERBOT_GEAR2_MAP_CAPE);
		}
		return -1;
	}

