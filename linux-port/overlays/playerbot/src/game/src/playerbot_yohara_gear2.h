	// The worn piece off into the bag (NULL: it could not come off).
	LPITEM TakeOffPlayerBotGear2Piece(LPCHARACTER ch, const TPlayerBotGear2Target& t)
	{
		LPITEM piece = ch->GetWear(t.bWearCell);
		if (!piece || piece->GetVnum() != t.dwInput || piece->isLocked() || piece->IsExchanging() || IsPlayerBotGearFrozen(ch))
			return NULL;
		if (ch->GetEmptyInventory(piece->GetSize()) < 0 || !ch->UnequipItem(piece) || piece->IsEquipped())
			return NULL;
		return piece;
	}


	// Jaharr / Kawuco / Angmur: the cube's way (the quest's for Angmur) - the materials and the Yang go, the roll, the
	// reward on success (Angmur: the piece's bonuses and stones on it); the piece goes, but on a failure that keeps it.
	bool CraftPlayerBotGear2Recipe(LPCHARACTER ch, TPlayerBotAIState& state, const TPlayerBotGear2Target& t, DWORD dwNow)
	{
		const TPlayerBotGear2Recipe& r = PLAYERBOT_GEAR2_RECIPES[t.iRecipe];
		if (CountPlayerBotFreeInventoryCells(ch) < PLAYERBOT_GEAR2_FREE_CELLS || GetPlayerBotGear2Spare(ch) < t.llGold ||
				!HasPlayerBotGear2Materials(ch, t))
			return false;
		LPITEM piece = TakeOffPlayerBotGear2Piece(ch, t);
		if (!piece)
			return false;
		const WORD cell = piece->GetCell();
		for (int m = 0; m < 5; ++m)
			if (t.adwMat[m] != 0)
				ch->RemoveSpecifyItem(t.adwMat[m], (ITEM_COUNT)t.aiCount[m]);
		if (t.llGold > 0)
			PlayerBotChangeGold(ch, -t.llGold);
		s_kPlayerBotGear2Stats.spentYang += t.llGold;
		// MT2009_PLUS_BOT_RUNES_V1: Jaharr's and Kawuco's are crafting-window recipes - a Runa Wykuwania Zbroi in the
		// slot (category 0, playerbot_runes.h); Angmur's is a quest's (always made)
		int chance = t.iPercent;
		if (t.bNpc == PLAYERBOT_GEAR2_NPC_JAHARR || t.bNpc == PLAYERBOT_GEAR2_NPC_KAWUCO)
			chance = std::min(100, chance + UsePlayerBotCraftRune(ch, 0, t.iPercent,
					t.bNpc == PLAYERBOT_GEAR2_NPC_KAWUCO ? 5 : 4, "gear2", t.dwReward));
		const bool success = number(1, 100) <= chance;
		DWORD made = 0;
		if (success)
		{
			LPITEM pkNew = ITEM_MANAGER::instance().CreateItem(t.dwReward, 1, 0, false);
			if (pkNew)
			{
				if (r.bKeepBonus)
					ITEM_MANAGER::CopyAllAttrTo(piece, pkNew);
				LogManager::instance().ItemLog(ch, pkNew, "PLAYERBOT_GEAR2", pkNew->GetName());
				ITEM_MANAGER::instance().RemoveItem(piece, "REMOVE (PLAYERBOT_GEAR2 CRAFT)");
				piece = NULL;
				pkNew->AddToCharacter(ch, TItemPos(INVENTORY, cell));
				ITEM_MANAGER::instance().FlushDelayedSave(pkNew);
				made = pkNew->GetID();
			}
			else
				sys_err("PLAYERBOT_GEAR2: reward not made pid=%u vnum=%u", ch->GetPlayerID(), t.dwReward);
		}
		else if (!r.bFailKeep)
		{
			ITEM_MANAGER::instance().RemoveItem(piece, "REMOVE (PLAYERBOT_GEAR2 FAIL)");
			piece = NULL;
		}
		if (piece && !piece->IsEquipped())
			ch->EquipItem(piece);
		LogManager::instance().CubeLog(ch->GetPlayerID(), ch->GetX(), ch->GetY(), t.dwReward, made, made ? 1 : 0, made ? 1 : 0);
		if (made)
			++s_kPlayerBotGear2Stats.crafted[t.bNpc];
		else
			++s_kPlayerBotGear2Stats.failed[t.bNpc];
		LogPlayerBotGear2Craft(ch, t, made ? "crafted" : (r.bFailKeep ? "failed (piece kept)" : "failed"), made, t.llGold);
		state.bEquipPending = true;
		state.dwNextEquipmentCheckTime = 0;
		return true;
	}

	// Seon-Pyeong: the engine's refine (DoRefine - the elite recipe, 100%, the stones and bonuses kept), the piece off
	// first; the equipment pass puts the new one on.
	bool UpgradePlayerBotGear2Elite(LPCHARACTER ch, TPlayerBotAIState& state, const TPlayerBotGear2Target& t)
	{
		if (CountPlayerBotFreeInventoryCells(ch) < PLAYERBOT_GEAR2_FREE_CELLS || GetPlayerBotGear2Spare(ch) < t.llGold ||
				!HasPlayerBotGear2Materials(ch, t))
			return false;
		LPITEM piece = TakeOffPlayerBotGear2Piece(ch, t);
		if (!piece)
			return false;
		const WORD cell = piece->GetCell();
		const long long goldBefore = (long long)ch->GetGold();
		const bool attempted = ch->DoRefine(piece, false);
		LPITEM after = ch->GetInventoryItem(cell);
		const bool success = attempted && after && after->GetVnum() == t.dwReward;
		if (after && !after->IsEquipped() && (success || after->GetVnum() == t.dwInput))
			ch->EquipItem(after);
		if (!attempted)
			return false;
		const long long paid = goldBefore - (long long)ch->GetGold();
		s_kPlayerBotGear2Stats.spentYang += paid;
		if (success)
			++s_kPlayerBotGear2Stats.crafted[t.bNpc];
		else
			++s_kPlayerBotGear2Stats.failed[t.bNpc];
		LogPlayerBotGear2Craft(ch, t, success ? "upgraded" : "upgrade failed", success && after ? after->GetID() : 0, paid);
		state.bEquipPending = true;
		state.dwNextEquipmentCheckTime = 0;
		return true;
	}

