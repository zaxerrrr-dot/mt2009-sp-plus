	int GetPlayerBotGear2ProtoLevel(const TItemTable* proto)
	{
		if (!proto)
			return 0;
		for (int i = 0; i < ITEM_LIMIT_MAX_NUM; ++i)
			if (proto->aLimits[i].bType == LIMIT_LEVEL)
				return (int)proto->aLimits[i].lValue;
		return 0;
	}

	// A result the bot may wear now (its level, its class).
	bool IsPlayerBotGear2RewardFor(LPCHARACTER ch, DWORD vnum)
	{
		const TItemTable* proto = ITEM_MANAGER::instance().GetTable(vnum);
		return proto && GetPlayerBotGear2ProtoLevel(proto) <= (int)ch->GetLevel() && IsPlayerBotProtoForCharacter(ch, proto);
	}

	// How much of a recipe's materials the bot holds, per mille (for the choice between rewards).
	int GetPlayerBotGear2Coverage(LPCHARACTER ch, const TPlayerBotGear2Target& t)
	{
		int have = 0, need = 0;
		for (int m = 0; m < 5; ++m)
		{
			if (t.adwMat[m] == 0)
				continue;
			need += t.aiCount[m];
			have += std::min(t.aiCount[m], (int)ch->CountSpecifyItem(t.adwMat[m]));
		}
		return need > 0 ? have * 1000 / need : 1000;
	}

	bool HasPlayerBotGear2Materials(LPCHARACTER ch, const TPlayerBotGear2Target& t)
	{
		for (int m = 0; m < 5; ++m)
			if (t.adwMat[m] != 0 && (int)ch->CountSpecifyItem(t.adwMat[m]) < t.aiCount[m])
				return false;
		return true;
	}

	long long GetPlayerBotGear2Spare(LPCHARACTER ch)
	{
		return (long long)ch->GetGold() - GetPlayerBotReservedGold(ch) - (long long)PLAYERBOT_SHOPPING_GOLD_FLOOR;
	}

	void FillPlayerBotGear2Target(TPlayerBotGear2Target& t, int recipe, BYTE cell)
	{
		const TPlayerBotGear2Recipe& r = PLAYERBOT_GEAR2_RECIPES[recipe];
		t.bNpc = r.bNpc;
		t.bWearCell = cell;
		t.iRecipe = recipe;
		t.dwInput = r.dwInput;
		t.dwReward = r.dwReward;
		t.llGold = r.llGold;
		t.iPercent = r.bPercent;
		for (int m = 0; m < 5; ++m)
		{
			t.adwMat[m] = r.mats[m].vnum;
			t.aiCount[m] = r.mats[m].count;
		}
	}

	// Seon-Pyeong: the engine's elite step of a worn +9 (a body armour or a weapon).
	bool FindPlayerBotGear2Elite(LPCHARACTER ch, BYTE cell, LPITEM piece, TPlayerBotGear2Target& out)
	{
		if (piece->GetRefinedVnum() == 0 || !IsEliteRefine(piece->GetRefineSet()) || (cell != WEAR_BODY && cell != WEAR_WEAPON))
			return false;
		const TRefineTable* recipe = CRefineManager::instance().GetRefineRecipe(piece->GetRefineSet());
		const TItemTable* next = ITEM_MANAGER::instance().GetTable(piece->GetRefinedVnum());
		if (!recipe || !next || !IsPlayerBotGear2RewardFor(ch, piece->GetRefinedVnum()))
			return false;
		if (cell == WEAR_WEAPON && GetPlayerBotWeaponHitDamageAt(NULL, next, ch) < GetPlayerBotWeaponHitDamageAt(NULL, piece->GetProto(), ch))
			return false;
		memset(&out, 0, sizeof(out));
		out.bNpc = PLAYERBOT_GEAR2_NPC_SEONPYEONG;
		out.bWearCell = cell;
		out.iRecipe = -1;
		out.dwInput = piece->GetVnum();
		out.dwReward = piece->GetRefinedVnum();
		out.llGold = recipe->cost;
		out.iPercent = recipe->prob;
		for (int m = 0; m < recipe->material_count && m < 5; ++m)
		{
			out.adwMat[m] = recipe->materials[m].vnum;
			out.aiCount[m] = recipe->materials[m].count;
		}
		out.bPieceReady = true;
		return true;
	}

	// The worn piece's next step, if it has one for this bot: Angmur first (always made, the bonuses kept - a level-66
	// armour +9 goes to 90 there rather than to Seon-Pyeong's 80), then Seon-Pyeong's step, then the best covered recipe
	// of Jaharr / Kawuco.
	bool FindPlayerBotGear2Target(LPCHARACTER ch, BYTE cell, TPlayerBotGear2Target& out)
	{
		LPITEM piece = ch->GetWear(cell);
		if (!piece || !piece->GetProto())
			return false;
		const DWORD vnum = piece->GetVnum();
		int best = -1, bestCover = -1;
		bool bestAngmur = false;
		const DWORD salt = PlayerBotNavHash(ch->GetPlayerID() ^ 0x47454152U);
		for (int i = 0; i < PLAYERBOT_GEAR2_RECIPE_COUNT; ++i)
		{
			const TPlayerBotGear2Recipe& r = PLAYERBOT_GEAR2_RECIPES[i];
			if (r.dwInput != vnum)
				continue;
			// Jaharr: the attack helmets (the plan's G1) - the Dragona ones (fail_keep) are the players'.
			if (r.bNpc == PLAYERBOT_GEAR2_NPC_JAHARR && (r.bFailKeep || (int)ch->GetLevel() < PLAYERBOT_GEAR2_HELM_LEVEL))
				continue;
			if (!IsPlayerBotGear2RewardFor(ch, r.dwReward))
				continue;
			TPlayerBotGear2Target t;
			memset(&t, 0, sizeof(t));
			FillPlayerBotGear2Target(t, i, cell);
			const bool angmur = r.bNpc == PLAYERBOT_GEAR2_NPC_ANGMUR;
			const int cover = GetPlayerBotGear2Coverage(ch, t) * 16 + (int)((salt + (DWORD)i) % 16U);
			if (best < 0 || (angmur && !bestAngmur) || (angmur == bestAngmur && cover > bestCover))
			{
				best = i;
				bestCover = cover;
				bestAngmur = angmur;
			}
		}
		if (!bestAngmur && FindPlayerBotGear2Elite(ch, cell, piece, out))
			return true;
		if (best < 0)
			return false;
		memset(&out, 0, sizeof(out));
		FillPlayerBotGear2Target(out, best, cell);
		const int plus = (int)piece->GetRefineLevel();
		out.bPieceReady = bestAngmur || plus >= std::min<int>(9, (int)GetPlayerBotRefineTarget(ch, piece));
		return true;
	}

	TPlayerBotGear2Bot& GetPlayerBotGear2(LPCHARACTER ch, DWORD dwNow, bool readReady = true)
	{
		TPlayerBotGear2Bot& b = s_mapPlayerBotGear2[ch->GetPlayerID()];
		if (b.dwPlanAt == 0 || dwNow - b.dwPlanAt >= PLAYERBOT_GEAR2_PLAN_MS)
		{
			b.dwPlanAt = dwNow ? dwNow : 1;
			b.targets.clear();
			if (IsPlayerBotGear2Bot(ch) && !IsPlayerBotGear2Off())
			{
				static const BYTE s_aCells[3] = { WEAR_HEAD, WEAR_BODY, WEAR_WEAPON };
				for (int c = 0; c < 3; ++c)
				{
					TPlayerBotGear2Target t;
					if (FindPlayerBotGear2Target(ch, s_aCells[c], t))
						b.targets.push_back(t);
				}
			}
		}
		// the purse and the bag change between plans: "ready" is read now (not for the keep / market hooks, asked per item)
		for (size_t i = 0; readReady && i < b.targets.size(); ++i)
		{
			TPlayerBotGear2Target& t = b.targets[i];
			t.bReady = t.bPieceReady && GetPlayerBotGear2Spare(ch) >= t.llGold && HasPlayerBotGear2Materials(ch, t);
		}
		return b;
	}

	const std::vector<TPlayerBotGear2Target>* GetPlayerBotGear2Targets(LPCHARACTER ch)
	{
		if (!IsPlayerBotGear2Bot(ch))
			return NULL;
		const TPlayerBotGear2Bot& b = GetPlayerBotGear2(ch, get_dword_time(), false);
		return b.targets.empty() ? NULL : &b.targets;
	}

	// ------------------------------------------------------------ the hooks: keep, hunt, market

	int GetPlayerBotGear2MaterialKeep(LPCHARACTER ch, DWORD vnum)
	{
		const std::vector<TPlayerBotGear2Target>* targets = vnum ? GetPlayerBotGear2Targets(ch) : NULL;
		if (!targets)
			return 0;
		int keep = 0;
		for (size_t i = 0; i < targets->size(); ++i)
			for (int m = 0; m < 5; ++m)
				if ((*targets)[i].adwMat[m] == vnum)
					keep += (*targets)[i].aiCount[m] * ((*targets)[i].iPercent < 100 ? 2 : 1);
		return keep;
	}

	// MT2009_PLUS_BOT_MELEY_RUNS_V1: how many of a material the bot's targets take for one attempt (playerbot_dgrun_meley.h:
	// a member's lack and its spare for the lair's share). 0 with the errand off.
	int GetPlayerBotGear2MaterialNeed(LPCHARACTER ch, DWORD vnum)
	{
		if (!ch || !vnum || IsPlayerBotGear2Off())
			return 0;
		const std::vector<TPlayerBotGear2Target>* targets = GetPlayerBotGear2Targets(ch);
		if (!targets)
			return 0;
		int need = 0;
		for (size_t i = 0; i < targets->size(); ++i)
			for (int m = 0; m < 5; ++m)
				if ((*targets)[i].adwMat[m] == vnum)
					need += (*targets)[i].aiCount[m];
		return need;
	}

	void CollectPlayerBotGear2Missing(LPCHARACTER ch, std::map<DWORD, int>& missing)
	{
		const std::vector<TPlayerBotGear2Target>* targets = GetPlayerBotGear2Targets(ch);
		if (!targets)
			return;
		std::map<DWORD, int> need;
		for (size_t i = 0; i < targets->size(); ++i)
			for (int m = 0; m < 5; ++m)
				if ((*targets)[i].adwMat[m] != 0)
					need[(*targets)[i].adwMat[m]] += (*targets)[i].aiCount[m];
		for (std::map<DWORD, int>::const_iterator it = need.begin(); it != need.end(); ++it)
		{
			const int lack = it->second - (int)ch->CountSpecifyItem(it->first);
			if (lack > 0)
				missing[it->first] += lack;
		}
	}

	void CollectPlayerBotGear2WantedMaterials(LPCHARACTER ch, std::set<DWORD>& out)
	{
		std::map<DWORD, int> missing;
		CollectPlayerBotGear2Missing(ch, missing);
		for (std::map<DWORD, int>::const_iterator it = missing.begin(); it != missing.end(); ++it)
			out.insert(it->first);
	}

	bool WantsPlayerBotGear2Offer(LPCHARACTER ch, LPITEM offer)
	{
		if (!ch || !offer || IsPlayerBotGear2Off())
			return false;
		std::map<DWORD, int> missing;
		CollectPlayerBotGear2Missing(ch, missing);
		std::map<DWORD, int>::const_iterator it = missing.find(offer->GetVnum());
		return it != missing.end() && (int)offer->GetCount() <= std::max(it->second * 2, 1);
	}

	int GetPlayerBotDropkiPursePercent(LPCHARACTER ch, int base);	// MT2009_PLUS_BOT_DROPKI_V1 (playerbot_dropki.h): a Dropki spends more on its build

	bool CanPlayerBotPayForGear2Offer(LPCHARACTER ch, LPITEM offer, long long price)
	{
		if (!ch || !offer || price <= 0)
			return false;
		const long long fair = (long long)GetPlayerBotShopAskingPrice(offer);
		return (fair <= 0 || price * 100 <= fair * PLAYERBOT_GEAR2_BUY_OVER_PERCENT) &&
				price <= GetPlayerBotGear2Spare(ch) * GetPlayerBotDropkiPursePercent(ch, PLAYERBOT_GEAR2_BUY_PURSE_PERCENT) / 100;	// MT2009_PLUS_BOT_DROPKI_V1
	}

	void NotePlayerBotGear2Bought(LPCHARACTER ch, DWORD vnum, long long price)
	{
		if (!ch || GetPlayerBotGear2MaterialKeep(ch, vnum) <= 0)
			return;
		++s_kPlayerBotGear2Stats.bought;
		s_kPlayerBotGear2Stats.boughtYang += std::max<long long>(0, price);
		sys_log(0, "PLAYERBOT_GEAR2: bought pid=%u name=%s vnum=%u price=%lld have=%u keep=%d",
				ch->GetPlayerID(), ch->GetName(), vnum, price, (unsigned int)ch->CountSpecifyItem(vnum),
				GetPlayerBotGear2MaterialKeep(ch, vnum));
	}

