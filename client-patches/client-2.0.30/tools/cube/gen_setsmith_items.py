# -*- coding: utf-8 -*-
# MT2009_PLUS_CUBE_RENEWAL_V2 - the pieces the set blacksmiths (20475-20479) work on, for the crafting window's
# "Uszlachetnienie" tree (root/uicuberenewal.py): writes client-2.0.30/root/cube_setsmith_data.py (GENERATED).
#
# The server's rule (server-patches/ysets, item.cpp Mt2009YSetsPart + Mt2009YSetsCubeGear): a weapon (not an arrow),
# a body armour or a helmet whose level limit is 75 or more, refined to +7 or more (CItem::GetRefineLevel: the number
# after the last "+" of item_proto.name). The client cannot list its item_proto, so the window takes this list (and
# adds any piece of the bag that fits the same rule - an item newer than the list still shows when the player has it).
# A vnum the client's item_proto does not have is left out (the window could not name it).
#
#   1. the server's rows (read only - a SELECT on the world database of a running stack):
#      docker exec mt2009plustest-db sh -c 'mariadb -uroot -p"$MARIADB_ROOT_PASSWORD" --default-character-set=latin1 \
#        -N -B -e "SELECT vnum,name,locale_name,type,subtype,limittype0,limitvalue0,limittype1,limitvalue1 \
#        FROM world.item_proto WHERE (type=1 AND subtype<>6) OR (type=2 AND subtype IN (0,1))"' > /tmp/setsmith.tsv
#   2. docker run --rm -v /opt/metin2:/opt/metin2 -v /tmp:/tmp m2pack-lzo python3 \
#        <repo>/client-patches/client-2.0.30/tools/cube/gen_setsmith_items.py /tmp/setsmith.tsv <client pack dir>
#      (<client pack dir>: a build's pack directory with dbdata.index/.data - the client's item_proto)
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, '/opt/metin2/cache/tcm/tz')
sys.path.insert(0, HERE)
import cube_files  # noqa: E402

OUT = os.path.join(cube_files.ROOT, 'cube_setsmith_data.py')
ITEM_KEY = (173217, 72619434, 408587239, 27973291)
RECORD = 184
LIMIT_LEVEL = 1
MIN_LEVEL = 75
MIN_REFINE = 7


def refine_level(name):
    p = name.rfind('+')
    if p < 0:
        return 0
    m = re.match(r'\d+', name[p + 1:])
    return int(m.group()) if m else 0


def part_of(typ, sub):
    if typ == 1 and sub != 6:
        return 1
    if typ == 2 and sub == 0:
        return 2
    if typ == 2 and sub == 1:
        return 3
    return 0


def level_of(limits):
    for (lt, lv) in limits:
        if lt == LIMIT_LEVEL:
            return lv
    return 0


def server_pieces(tsv):
    out = {}
    with open(tsv, 'rb') as f:
        for line in f:
            p = line.decode('latin1').rstrip('\r\n').split('\t')
            if len(p) < 9:
                continue
            vnum, name = int(p[0]), p[1]
            typ, sub = int(p[3]), int(p[4])
            part = part_of(typ, sub)
            lvl = level_of(((int(p[5]), int(p[6])), (int(p[7]), int(p[8]))))
            if part and lvl >= MIN_LEVEL and refine_level(name) >= MIN_REFINE:
                out[vnum] = (part, lvl)
    return out


def client_proto(pack_dir):
    """{vnum: (name, type, subtype, level limit)} of the client's item_proto (dbdata pack)"""
    import m2pack
    f, v, ents = m2pack.read_index(os.path.join(pack_dir, 'dbdata.index'))
    with open(os.path.join(pack_dir, 'dbdata.data'), 'rb') as fp:
        dat = fp.read()
    e = [x for x in ents if x['name'] == 'gamedata/item_proto'][0]
    b = m2pack.read_entry(dat, e)
    assert b[:4] == b'MIPX'
    ver, stride, cnt, size = struct.unpack_from('<IIII', b, 4)
    assert stride == RECORD, stride
    raw = m2pack.mcoz_decode(b[20:], ITEM_KEY)
    out = {}
    for i in range(cnt):
        r = raw[i * RECORD:(i + 1) * RECORD]
        vnum = struct.unpack_from('<I', r, 0)[0]
        name = r[8:41].split(b'\0')[0].decode('cp1250', 'replace')
        typ, sub = r[74], r[75]
        lt0, lv0, lt1, lv1 = struct.unpack_from('<BiBi', r, 114)
        out[vnum] = (name, typ, sub, level_of(((lt0, lv0), (lt1, lv1))))
    return out


def main():
    tsv, pack_dir = sys.argv[1:3]
    server = server_pieces(tsv)
    client = client_proto(pack_dir)
    parts = {1: [], 2: [], 3: []}
    missing = []
    for vnum in sorted(server):
        if vnum not in client:
            missing.append(vnum)
            continue
        parts[server[vnum][0]].append(vnum)
    lines = [
        '# MT2009_PLUS_CUBE_RENEWAL_V2: GENERATED by tools/cube/gen_setsmith_items.py - do not edit. The pieces the set',
        '# blacksmiths (20475-20479) work on (server-patches/ysets: a weapon, a body armour or a helmet of level 75+',
        '# refined to +7 or more), part -> vnums; root/uicuberenewal.py builds the "Uszlachetnienie" tree from them.',
        '',
        'PIECES = {',
    ]
    for part in (1, 2, 3):
        vs = parts[part]
        lines.append('\t%d : (' % part)
        for i in range(0, len(vs), 16):
            lines.append('\t\t' + ' '.join('%d,' % v for v in vs[i:i + 16]))
        lines.append('\t),')
    lines.append('}')
    data = ('\n'.join(lines) + '\n').encode('ascii')
    old = open(OUT, 'rb').read() if os.path.exists(OUT) else None
    if old != data:
        with open(OUT, 'wb') as f:
            f.write(data)
    print('%s: weapons %d, armours %d, helmets %d; not in the client: %s -> %s' % (
        os.path.basename(OUT), len(parts[1]), len(parts[2]), len(parts[3]), missing or 'none',
        'unchanged' if old == data else 'written'))


if __name__ == '__main__':
    main()
