# The python (uiwiki.py, tooltipmodel.py, the hooks) and the side bar's icon (mt2009_ui/sidebar/wiki_0x.tga) travel in
# client-2.0.30/root like every root change (build57.py).
#
#   docker run --rm -v /opt/metin2:/opt/metin2 m2pack-lzo python3 \
#     <repo>/client-patches/client-2.0.30/tools/wikiv2/build_wikiv2_pack.py <BASE pack dir> <OUT pack dir> [--check]
#
# clientY.sh: after the last pack builder (before the verify loop):
#   S_wikiv2_pack() { docker run --rm -v /opt/metin2:/opt/metin2 m2pack-lzo python3 $T/wikiv2/build_wikiv2_pack.py \
#     $C/azbase $C/out/pack; }; step wikiv2_pack $C/wikiv2.json S_wikiv2_pack
# BASE: the client's packs so far (Index is read from OUT if an earlier step wrote one there, else from BASE); OUT:
# where wikiv2.index / wikiv2.data and the Index go - its "*" / "wikiv2" pair at the end (every name is new to the
# client, so the pack's place does not matter; the front belongs to fireghost). Every entry written is read back; a
# name another pack has already stops the build. Idempotent: the same content gives "unchanged", the Index line is
# not added twice. --check only measures.
import json
import os
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, '/opt/metin2/cache/tcm/tz')
sys.path.insert(0, '/opt/metin2/cache/arezzo-work/client/az58')

PACK = 'wikiv2'
DATA = os.path.normpath(os.path.join(HERE, '..', '..', 'wikiv2'))
TEXT = ('.txt', '.sub', '.mse')
DATA_FILES = ('locale/common/wiki/items.txt', 'locale/common/wiki/mobs.txt', 'locale/common/wiki/chests.txt',
	'locale/common/wiki/crafting.txt')
ZIP_LIMIT = 29 * 1024 * 1024


def items():
	"""{in-pack name: (bytes, ctype)} of client-2.0.30/wikiv2 (names lower-case, as the packs keep them)"""
	out = {}
	for root, dirs, files in os.walk(DATA):
		for f in files:
			path = os.path.join(root, f)
			rel = os.path.relpath(path, DATA).replace(os.sep, '/')
			if rel.startswith('d_/'):
				name = ('d:' + rel[2:]).lower()
			elif rel.startswith('locale/'):
				name = rel.lower()
			else:
				continue
			out[name] = (open(path, 'rb').read(), 2 if name.endswith(TEXT) else 1)
	missing = [n for n in DATA_FILES if n not in out]
	if missing:
		raise SystemExit('the wiki data is missing (run gen_wiki_data.py): %s' % missing)
	for n in DATA_FILES:
		head = out[n][0][:200]
		if b'GENERATED' not in head:
			raise SystemExit('%s: not the generator\'s file' % n)
	return out


def main():
	import m2pack
	import packlib
	args = [a for a in sys.argv[1:] if not a.startswith('--')]
	check = '--check' in sys.argv
	base, out = args[:2]
	rd = packlib.rd
	want = items()
	raw = dict((k, b) for k, (b, c) in want.items())
	report = {'files': len(want), 'data_files': dict((n, len(want[n][0])) for n in DATA_FILES)}

	clash = {}
	for d in (base, out):
		if not os.path.isdir(d):
			continue
		for p in sorted(f[:-6] for f in os.listdir(d) if f.endswith('.index')):
			if p == PACK:
				continue
			for e in m2pack.read_index(os.path.join(d, p + '.index'))[2]:
				if e['name'] in want:
					clash.setdefault(p, []).append(e['name'])
	if clash:
		raise SystemExit('names other packs have: %s' % dict((p, n[:5]) for p, n in clash.items()))

	built = False
	if os.path.exists(os.path.join(out, PACK + '.index')):
		f, v, ents = m2pack.read_index(os.path.join(out, PACK + '.index'))
		dat = rd(os.path.join(out, PACK + '.data'))
		if (dict((e['name'], m2pack.read_entry(dat, e)) for e in ents) == raw and
				all(e['ctype'] == want[e['name']][1] for e in ents)):
			report[PACK] = 'unchanged'
			built = True
	if not built:
		if check:
			size = sum(len(m2pack.encode_entry(b, c)) for b, c in want.values())
			report[PACK] = dict(files=len(want), data_kb=round(size / 1e3, 1))
		else:
			tmpl = m2pack.read_index(os.path.join(base, 'gf_mobs.index'))[2][-1]['raw']
			ti, td = os.path.join(out, PACK + '.index.tmp'), os.path.join(out, PACK + '.data.tmp')
			packlib.repack_add_typed(None, None, {}, want, ti, td, tmpl)
			os.replace(ti, os.path.join(out, PACK + '.index'))
			os.replace(td, os.path.join(out, PACK + '.data'))
			f, v, ents = m2pack.read_index(os.path.join(out, PACK + '.index'))
			dat = rd(os.path.join(out, PACK + '.data'))
			got = {}
			for e in ents:
				assert zlib.crc32(dat[e['pos']:e['pos'] + e['size']]) & 0xffffffff == e['dcrc'], e['name']
				assert e['fcrc'] == zlib.crc32(e['name'].encode('cp1252')) & 0xffffffff, e['name']
				assert e['ctype'] == want[e['name']][1], e['name']
				got[e['name']] = m2pack.read_entry(dat, e)
			assert got == raw, 'read-back differs'
			report[PACK] = dict(entries=len(ents), data_kb=round(len(dat) / 1e3, 1), under_zip_limit=len(dat) < ZIP_LIMIT)

	# Index: "*" + "wikiv2" at the end
	if not check:
		ix_path = os.path.join(out, 'Index') if os.path.exists(os.path.join(out, 'Index')) else os.path.join(base, 'Index')
		ix = rd(ix_path)
		nl = b'\r\n' if b'\r\n' in ix else b'\n'
		lines = ix.replace(b'\r\n', b'\n').split(b'\n')
		while lines and lines[-1].strip() == b'':
			lines.pop()
		if lines[0].strip() != b'PACK':
			raise SystemExit('Index: the first line is not PACK')
		if PACK.encode() in [l.strip() for l in lines]:
			new = ix
		else:
			lines += [b'*', PACK.encode()]
			new = nl.join(lines) + (nl if ix.endswith((b'\n', b'\r\n')) else b'')
		if new != ix or ix_path != os.path.join(out, 'Index'):
			open(os.path.join(out, 'Index'), 'wb').write(new)
			report['Index'] = 'written'
		else:
			report['Index'] = 'unchanged'
	print(json.dumps(report, indent=1))


if __name__ == '__main__':
	main()
