def put_block(path, block, anchor):
    text = open(path, encoding='utf-8', newline='').read()
    assert '\r\n' not in text, path
    start, end = u'# >>> %s' % MARK, u'# <<< %s\n' % MARK
    if start in text:
        a = text.index(start)
        b = text.index(end, a) + len(end)
        text = text[:a] + block + text[b:]
    else:
        assert text.count(anchor) == 1, anchor
        text = text.replace(anchor, block + anchor)
    open(path, 'w', encoding='utf-8', newline='').write(text)


def costume_sets_txt(path, sets):
    raw = open(path, encoding='utf-8', newline='').read()
    nl = '\r\n' if '\r\n' in raw else '\n'
    lines = raw.replace('\r\n', '\n').split('\n')
    names = set(s['name'] for s in sets) | set(r[1] for r in A.REMOVED_SETS)   # V2: the removed ones go too
    keep = [l for l in lines if l.split('\t')[0] not in names and MARK not in l]
    while keep and keep[-1] == '':
        keep.pop()
    keep.append(u'# %s: the Arezzo costume sets (client-patches/client-2.0.30/tools/azcostume) - a costume (m)/(k)'
                % MARK)
    keep.append(u'# and a helmet (m)/(k) of one set give the same bonus as every set here; weapon / sash skins are looks only (%s).' % MARK)
    for s in sets:
        keep.append(u'%s\t%s\t%s' % (s['name'], ','.join(str(v) for v in s['bodies']), ','.join(str(v) for v in s['hairs'])))
    open(path, 'w', encoding='utf-8', newline='').write(nl.join(keep) + nl)
    return keep


def costume_sets_py(path, txt_lines):
    """SETS = (...) of root/costume_sets.py again from costume_sets.txt (its header and the code after stay)."""
    text = open(path, encoding='latin-1', newline='').read()
    assert '\r\n' not in text, path
    a = text.index('SETS = (\n')
    b = text.index('\n)\n', a) + 3
    rows = []
    for l in txt_lines:
        if not l or l.startswith('#'):
            continue
        name, bodies, hairs = l.split('\t')[:3]
        rows.append('\t((%s,), (%s,)),\t# %s' % (bodies, hairs, name))
    text = text[:a] + 'SETS = (\n' + '\n'.join(rows) + '\n)\n' + text[b:]
    open(path, 'w', encoding='latin-1', newline='').write(text)


