# --- icons for the web shop: TGA (types 2/10, 24/32 bit) or PNG -> PNG --------------------------
def tga_rgba(b):
    idlen, cmtype, itype = b[0], b[1], b[2]
    w, h, bpp, desc = struct.unpack_from('<HHBB', b, 12)
    assert cmtype == 0 and itype in (2, 10) and bpp in (24, 32), (cmtype, itype, bpp)
    px = bpp // 8
    pos = 18 + idlen
    data = bytearray()
    need = w * h * px
    if itype == 2:
        data = b[pos:pos + need]
    else:
        while len(data) < need:
            c = b[pos]
            pos += 1
            n = (c & 0x7f) + 1
            if c & 0x80:
                data += b[pos:pos + px] * n
                pos += px
            else:
                data += b[pos:pos + px * n]
                pos += px * n
    rows = []
    for y in range(h):
        sy = y if desc & 0x20 else h - 1 - y
        row = bytearray()
        for x in range(w):
            p = data[(sy * w + x) * px:(sy * w + x + 1) * px]
            row += bytes((p[2], p[1], p[0], p[3] if px == 4 else 255))
        rows.append(bytes(row))
    return w, h, rows


def png_bytes(w, h, rows):
    def chunk(t, d):
        return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    raw = b''.join(b'\0' + r for r in rows)
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 6, 0, 0, 0)) +
            chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


def web_icon(icon_key):
    src = os.path.join(ICON_SRC, icon_key)
    b = open(src, 'rb').read()
    if b[:8] == b'\x89PNG\r\n\x1a\n':
        return b
    return png_bytes(*tga_rgba(b))


