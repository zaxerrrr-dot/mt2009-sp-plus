# -*- coding: utf-8 -*-
# MT2009_PLUS_NPC_LOCATION_HELPER_V1 - the client build's part of Lokalizator NPC (Autor: Best Studio). No new pack;
# existing packs get:
#   gamedata  gamedata/item_list.txt                  the three items' lines (patch_npcloc_client.py)
#   dbdata    gamedata/item_proto, locale/pl/itemdesc.txt   their records / descriptions (from the server's SQL)
#   locale    locale/common/map/npc_location_helper/{npc_location_helper,map_mob_list,mob_drop_item,event_npc_list}.txt
#             and locale/common/map/<map_dir>_point.txt  (client-2.0.30/npcloc/locale/..., GENERATED by
#             tools/npcloc/gen_npcloc_data.py from our world; uinpclocationhelper.py reads them through
#             npcLocationHelper.ReadTextFile)
#   root      the 12 .sub files of the window's title-bar buttons the full install lacks (client-2.0.30/npcloc/
#             d_/ymir work/ui/game/npc_location_helper/button_{switch_to_npc_location_helper,switch_to_small,
#             title_bar_expand,title_bar_shrink}_{default,over,down}.sub, from the package). The other 80 pictures
#             the window and the direction effect use (ui_assets.txt: npc_location_01.dds, the other .sub, pattern/
#             btn_*.tga, effect/etc/npc_location/*) are already in the full install's base pack "etc".
# The icons (root/icon/item/79667.tga, 79669.tga) and the python (root/uinpclocationhelper.py, root/uiscript/
# npclocationhelper_*.py) travel in client-2.0.30/root like every root change (build57.py).
# BUILD ORDER - shares gamedata / dbdata / locale / root: after every other step that patches them (after ../kamienie),
# on the same OUT (a pack already in OUT - an earlier step changed it - is the one patched):
#
#   docker run --rm -v /opt/metin2:/opt/metin2 m2pack-lzo python3 \
#     <repo>/client-patches/client-2.0.30/tools/npcloc/build_npcloc_packs.py <BASE pack dir> <OUT pack dir> [--check]
#
# clientY.sh: after the kamienie line,
#   # MT2009_PLUS_NPC_LOCATION_HELPER_V1: Lokalizator NPC - items in gamedata/dbdata, map data in locale, UI in root
#   docker run --rm -v /opt/metin2:/opt/metin2 m2pack-lzo python3 $T/npcloc/build_npcloc_packs.py $C/azbase \
#     $C/out/pack > $C/npcloc.json
# and npcloc/verify_npcloc.py in the verify loop (its list of scripts). Every entry written is read back. Idempotent:
# a second run gives "unchanged". A name already in the full install's base pack "etc" (--etc=<dir with etc.index>,
# default /opt/metin2/cache/exebuild/smoke/client/pack, when there) is refused: it would shadow the install's file.
import json
import os
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, '/opt/metin2/cache/tcm/tz')
sys.path.insert(0, '/opt/metin2/cache/arezzo-work/client/az58')
sys.path.insert(0, HERE)
ZIP_LIMIT = 29 * 1024 * 1024
DATA = os.path.normpath(os.path.join(HERE, '..', '..', 'npcloc'))
TEXT = ('.txt', '.sub', '.mse')
ETC_DEFAULT = '/opt/metin2/cache/exebuild/smoke/client/pack'


def etc_dir():
    for a in sys.argv[1:]:
        if a.startswith('--etc='):
            return a[6:]
    return ETC_DEFAULT


def etc_names():
    """the names of the full install's base pack etc (None when that pack is not here)"""
    import m2pack
    p = os.path.join(etc_dir(), 'etc.index')
    if not os.path.exists(p):
        return None
    return set(e['name'] for e in m2pack.read_index(p)[2])


def added_files():
    """pack -> {in-pack name: bytes} of the files this step adds (names lower-case as the packs keep them)"""
    out = {'locale': {}, 'root': {}}
    for dp, dn, fn in os.walk(DATA):
        for f in fn:
            path = os.path.join(dp, f)
            rel = os.path.relpath(path, DATA).replace(os.sep, '/')
            if rel.startswith('locale/'):
                out['locale'][rel.lower()] = open(path, 'rb').read()
            elif rel.startswith('d_/'):
                out['root'][('d:' + rel[2:]).lower()] = open(path, 'rb').read()
    return out


def main():
    import m2pack
    import packlib
    import patch_npcloc_client as pc
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    check = '--check' in sys.argv
    base, out = args[:2]
    rd = packlib.rd
    report = {}

    def src_of(pack):
        return out if os.path.exists(os.path.join(out, pack + '.index')) else base

    def write(pack, src, rep, add, ents, dat):
        tmp_i, tmp_d = os.path.join(out, pack + '.index.nl'), os.path.join(out, pack + '.data.nl')
        r = packlib.repack_add_typed(os.path.join(src, pack + '.index'), os.path.join(src, pack + '.data'), rep, add,
                                     tmp_i, tmp_d, ents[-1]['raw'])
        os.replace(tmp_i, os.path.join(out, pack + '.index'))
        os.replace(tmp_d, os.path.join(out, pack + '.data'))
        f, v, nw = m2pack.read_index(os.path.join(out, pack + '.index'))
        nd = rd(os.path.join(out, pack + '.data'))
        names = [e['name'] for e in nw]
        assert len(set(names)) == len(names), pack
        got = {}
        for e in nw:
            assert zlib.crc32(nd[e['pos']:e['pos'] + e['size']]) & 0xffffffff == e['dcrc'], (pack, e['name'])
            got[e['name']] = m2pack.read_entry(nd, e)
        for n, b in list(rep.items()) + [(k, b) for k, (b, c) in add.items()]:
            assert got[n] == b, (pack, n)
        for e in ents:
            if e['name'] not in rep:
                assert got[e['name']] == m2pack.read_entry(dat, e), (pack, e['name'])
        return dict(old=r[0], added=r[1], replaced=r[2], entries=len(nw), data_mb=round(len(nd) / 1e6, 2),
                    under_zip_limit=len(nd) < ZIP_LIMIT)

    # every name this step adds must be new to every pack but the one it goes to
    files = added_files()
    elsewhere = {}
    for d in (base, out):
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            if f.endswith('.index'):
                for e in m2pack.read_index(os.path.join(d, f))[2]:
                    elsewhere.setdefault(e['name'], set()).add(f[:-6])
    for pack, fs in files.items():
        clash = sorted(n for n in fs if elsewhere.get(n, set()) - {pack})
        assert not clash, (pack, clash[:5])
    etc = etc_names()
    if etc is not None:
        clash = sorted(n for fs in files.values() for n in fs if n in etc)
        assert not clash, ('in the base pack etc', clash[:5])
    report['etc_pack_checked'] = etc is not None

    jobs = {'gamedata': [('gamedata/item_list.txt', pc.item_list)],
            'dbdata': [('gamedata/item_proto', pc.item_proto), ('locale/pl/itemdesc.txt', pc.itemdesc)],
            'locale': [], 'root': []}
    for pack, patches in jobs.items():
        src = src_of(pack)
        f, v, ents = m2pack.read_index(os.path.join(src, pack + '.index'))
        dat = rd(os.path.join(src, pack + '.data'))
        have = dict((e['name'], e) for e in ents)
        rep, add = {}, {}
        for n, fn in patches:
            b = m2pack.read_entry(dat, have[n])
            nb, changed = fn(b)
            if nb != b:
                rep[n] = nb
        for n, b in sorted(files.get(pack, {}).items()):
            if n in have:
                if m2pack.read_entry(dat, have[n]) != b:
                    rep[n] = b
            else:
                add[n] = (b, 2 if n.endswith(TEXT) else 1)
        if not rep and not add:
            report[pack] = 'unchanged'
        elif check:
            report[pack] = dict(replace=sorted(rep), add=len(add))
        else:
            report[pack] = write(pack, src, rep, add, ents, dat)
            report[pack]['replaced_names'] = sorted(rep)
    print(json.dumps(report, indent=1))


if __name__ == '__main__':
    main()
