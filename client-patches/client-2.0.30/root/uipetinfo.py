# item tooltips (uitooltip.py AddItemData): egg, seal, cage, skill book
def _AppendPetLines(tt, pet, metinSlot):
	now = Now()
	tt.AppendTextLine(pet.name, tt.SPECIAL_TITLE_COLOR)
	if pet.IsChampion():
		tt.AppendTextLine(T("TT_LEVEL_CHAMPION") % (pet.level, pet.championLevel), tt.TITLE_COLOR)
	else:
		tt.AppendTextLine(T("TT_LEVEL") % pet.level, tt.TITLE_COLOR)
	tt.AppendTextLine(T("TT_STAGE") % StageName(pet.evolution), tt.NORMAL_COLOR)
	if pet.type:
		tt.AppendTextLine(T("TT_TYPE") % TypeName(pet.type), tt.NORMAL_COLOR)
	tt.AppendTextLine(T("TT_AGE") % Days(pet.AgeSeconds(now)), tt.NORMAL_COLOR)
	if pet.lifeEnd and pet.lifeEnd <= now:
		tt.AppendTextLine(T("TT_DEAD"), tt.NEGATIVE_COLOR)
	else:
		tt.AppendTextLine(T("TT_LIFE") % (Duration(pet.LifeLeft()), Duration(pet.maxLife)), tt.CONDITION_COLOR)
	tt.AppendSpace(5)
	tt.AppendTextLine("%s %s" % (T("HP"), T("PERCENT") % Pct1(pet.hp)), tt.SPECIAL_POSITIVE_COLOR)
	tt.AppendTextLine("%s %s" % (T("DEF"), T("PERCENT") % Pct1(pet.defence)), tt.SPECIAL_POSITIVE_COLOR)
	tt.AppendTextLine("%s %s" % (T("SP"), T("PERCENT") % Pct1(pet.sp)), tt.SPECIAL_POSITIVE_COLOR)
	if pet.IsChampion():
		tt.AppendTextLine("%s %s" % (T("RES"), T("PERCENT") % Pct1(pet.res)), tt.SPECIAL_POSITIVE_COLOR2)
		tt.AppendTextLine("%s %s" % (T("BLOCK_PEN"), T("PERCENT") % Pct1(pet.blockPen)), tt.SPECIAL_POSITIVE_COLOR2)
		tt.AppendTextLine("%s %s" % (T("PRECISION"), T("PERCENT") % Pct1(pet.precision)), tt.SPECIAL_POSITIVE_COLOR2)
	tt.AppendSpace(5)
	tt.AppendTextLine(T("TT_SLOTS") % pet.skillSlots, tt.NORMAL_COLOR)
	for slot in xrange(min(SKILL_SLOTS, pet.skillSlots)):
		(sk, lv, cool) = GetSkill(pet.id, slot)
		if sk:
			tt.AppendTextLine(T("TT_SKILL") % (SkillInfo(sk)[0], lv), tt.SPECIAL_POSITIVE_COLOR)
	if pet.IsChampion():
		for slot in xrange(POTENTIAL_SLOTS):
			(egg, sk, lv, end) = GetPotential(pet.id, slot)
			if sk and end > now:
				tt.AppendTextLine(T("POT_SKILL") % (SkillInfo(sk)[0], lv), tt.SPECIAL_POSITIVE_COLOR2)
	if pet.id == ActivePetId():
		tt.AppendTextLine(T("TT_SUMMONED"), tt.CONDITION_COLOR)


def ItemTooltip(tt, vnum, metinSlot):
	"""uitooltip AddItemData for an item of type ITEM_PET (37). The caller adds AdditionalTips and shows it."""
	item.SelectItem(vnum)
	t, sub = item.GetItemType(), item.GetItemSubType()
	sockets = [U32(s) for s in (metinSlot or [])] + [0, 0, 0]
	now = Now()
	tt.SetTitle(item.GetItemName())
	desc = item.GetItemDescription()
	if sub == PET_EGG:
		seal = item.GetValue(0) or PD.EGGS.get(vnum, 0)
		if seal in PD.SEALS:
			tt.AppendTextLine(T("TT_EGG_HATCH") % PD.SEALS[seal][2], tt.TITLE_COLOR)
		if sockets[0] > now:
			tt.AppendTextLine(T("TT_EGG_TIME") % Duration(sockets[0] - now), tt.CONDITION_COLOR)
		elif sockets[0]:
			tt.AppendTextLine(T("TT_EGG_EXPIRED"), tt.NEGATIVE_COLOR)
		if seal in PD.SEALS:
			species = PD.SEALS[seal][0]
			skills = [SkillInfo(s)[0] for s in PD.POTENTIAL.get(species, ())]
			if skills:
				tt.AppendSpace(5)
				tt.AppendDescription(T("TT_EGG_POTENTIAL") % ", ".join(skills), 26, tt.NORMAL_COLOR)
		tt.AppendSpace(5)
		tt.AppendDescription(desc, 26)
		item.SelectItem(vnum)
		return
	if sub == PET_UPBRINGING:
		pet = GetPet(sockets[2])
		if pet:
			_AppendPetLines(tt, pet, sockets)
		else:
			if vnum in PD.SEALS:
				tt.AppendTextLine(PD.SEALS[vnum][2], tt.TITLE_COLOR)
			if sockets[0] and sockets[0] <= now:
				tt.AppendTextLine(T("TT_DEAD"), tt.NEGATIVE_COLOR)
			elif sockets[0]:
				tt.AppendTextLine(T("TT_LIFE") % (Duration(sockets[0] - now), Duration(sockets[1])), tt.CONDITION_COLOR)
			elif sockets[1]:
				tt.AppendTextLine(T("TT_LIFE_MAX") % Duration(sockets[1]), tt.CONDITION_COLOR)
			if sockets[2]:
				tt.AppendTextLine(T("TT_NO_DATA"), tt.NORMAL_COLOR)
		tt.AppendSpace(5)
		tt.AppendDescription(desc, 26)
		item.SelectItem(vnum)
		return
	if sub == PET_BAG:
		if not sockets[2]:
			tt.AppendTextLine(T("TT_BAG_EMPTY"), tt.NORMAL_COLOR)
		else:
			if sockets[0] > now:
				tt.AppendTextLine(T("TT_BAG_TIME") % Duration(sockets[0] - now), tt.CONDITION_COLOR)
			else:
				tt.AppendTextLine(T("TT_BAG_EXPIRED"), tt.NEGATIVE_COLOR)
			pet = GetPet(sockets[2])
			if pet:
				tt.AppendSpace(5)
				_AppendPetLines(tt, pet, sockets)
			else:
				tt.AppendTextLine(T("TT_NO_DATA"), tt.NORMAL_COLOR)
		tt.AppendSpace(5)
		tt.AppendDescription(desc, 26)
		item.SelectItem(vnum)
		return
	if sub == PET_SKILL:
		sk = item.GetValue(0) or PD.BOOKS.get(vnum, 0)
		if sk in PD.SKILLS:
			name, icon, kind, cooldown, unit, book, sdesc = SkillInfo(sk)
			tt.AppendTextLine(T("TT_BOOK_SKILL") % name, tt.TITLE_COLOR)
			tt.AppendTextLine(T("SKILL_KIND_AUTO") if kind == 2 else T("SKILL_KIND_PASSIVE"), tt.CONDITION_COLOR)
			if kind == 2 and cooldown:
				tt.AppendTextLine(T("SKILL_COOLDOWN") % Duration(cooldown), tt.NORMAL_COLOR)
			tt.AppendSpace(5)
		tt.AppendDescription(desc, 26)
		tt.AppendDescription(T("SKILL_BOOK_HINT"), 26, tt.CONDITION_COLOR)
		item.SelectItem(vnum)
		return
	tt.AppendDescription(desc, 26)
	item.SelectItem(vnum)
