def SetLocks(owner, cells):
	cells = set(c for c in cells if c is not None and c >= 0)
	if cells:
		_locks[owner] = cells
	elif owner in _locks:
		del _locks[owner]
	_ApplyLocks()


def _ApplyLocks():
	global _applied, _appliedPage
	inven = _Inventory()
	if not inven:
		return
	try:
		wndItem = inven.wndItem
		page = getattr(inven, "inventoryPageIndex", 0)
	except Exception:
		return
	if not wndItem:
		return
	size = player.INVENTORY_PAGE_SIZE
	want = set()
	for cells in _locks.values():
		for c in cells:
			if page * size <= c < (page + 1) * size:
				want.add(c - page * size)
	freed = _applied - want if page == _appliedPage else _applied
	try:
		for local in freed:
			wndItem.SetCanMouseEventSlot(local)
		for local in want:
			wndItem.SetCantMouseEventSlot(local)
	except Exception:
		return
	if freed and hasattr(inven, "RefreshBagSlotWindow"):
		try:
			inven.RefreshBagSlotWindow()
		except Exception:
			pass
	_applied = want
	_appliedPage = page


def _AttachedAnyItem():
	"""MT2009_PLUS_PET_ADDEQ_DRAG_V1: (window, cell, vnum, count) of the item on the mouse - from the bag or from an
	Additional Equipment tab (books now live in Ksiegi: they were ignored when dragged onto a skill slot) - or None."""
	if not mouseModule.mouseController.isAttached():
		return None
	slotType = mouseModule.mouseController.GetAttachedType()
	cell = mouseModule.mouseController.GetAttachedSlotNumber()
	if slotType == player.SLOT_TYPE_INVENTORY:
		r = _AttachedBagItem()
		return (player.INVENTORY,) + r if r else None
	try:
		import uiekwipunek
		if not uiekwipunek.IsEkwSlotType(slotType):
			return None
		window = uiekwipunek.WindowOfSlotType(slotType)
	except Exception:
		return None
	if window is None or window < 0 or cell < 0:
		return None
	vnum = player.GetItemIndex(window, cell)
	if not vnum:
		return None
	return window, cell, vnum, mouseModule.mouseController.GetAttachedItemCount()


def _AttachedBagItem():
	"""(cell, vnum, count) of the bag item on the mouse, or None."""
	if not mouseModule.mouseController.isAttached():
		return None
	if mouseModule.mouseController.GetAttachedType() != player.SLOT_TYPE_INVENTORY:
		return None
	cell = mouseModule.mouseController.GetAttachedSlotNumber()
	if cell < 0 or cell >= BagCellCount():
		return None
	vnum = player.GetItemIndex(cell)
	if not vnum:
		return None
	return cell, vnum, mouseModule.mouseController.GetAttachedItemCount()


class TextToolTip(object):
	"""MT2009_PLUS_PET_EXP_TOOLTIP_V2: a few lines (the EXP balls, the book / gem icons, the mini window) in an ordinary
	game tooltip - its dark board under the text, so it reads as any other tooltip (was bare outlined text drawn over
	the window). Made on first use; SetLines / Show / Hide as before."""
	def __init__(self):
		self.tip = None
		self.lines = None

	def __Tip(self):
		if self.tip is None:
			import uiToolTip
			self.tip = uiToolTip.ToolTip(160)
			self.tip.HideToolTip()
		return self.tip

	def SetLines(self, lines):
		lines = list(lines or ())
		if lines == self.lines:
			return
		self.lines = lines
		tt = self.__Tip()
		tt.ClearToolTip()
		for text in lines:
			tt.AppendTextLine(text, tt.FONT_COLOR)

	def Show(self):
		if self.lines:
			tt = self.__Tip()
			if not tt.IsShow():
				tt.ShowToolTip()

	def Hide(self):
		if self.tip is not None and self.tip.IsShow():
			self.tip.HideToolTip()

	def IsShow(self):
		return self.tip is not None and self.tip.IsShow()


