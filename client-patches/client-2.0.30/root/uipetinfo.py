def _Event(obj, name, *extra):
	"""A callable for a ui event that holds the window only weakly (no reference cycle) and adds extra args first."""
	ref = _proxy(obj)

	def call(*args):
		try:
			return getattr(ref, name)(*(extra + args))
		except ReferenceError:
			return None
	return call


