	def PutReviveItem(self, cell, slot=-1):
		vnum = player.GetItemIndex(cell)
		t, sub = ItemKind(vnum)
		if t != ITEM_TYPE_GROWTH_PET or sub not in (PET_UPBRINGING, PET_PRIMIUM_FEEDSTUFF):
			Chat(T("REVIVE_WRONG"))
			return False
		if self.reviveDone:
			self.ClearRevive()
		if sub == PET_UPBRINGING:
			end = Socket(cell, 0)
			petId = Socket(cell, 2)
			if not petId:
				Chat(T("REVIVE_WRONG"))
				return False
			if end > Now():
				_Popup(T("REVIVE_ALIVE"))
				return False
			self.reviveCell = cell
			self.reviveSlot.SetItemSlot(0, vnum)
			self.reviveResultSlot.SetItemSlot(0, vnum)
			self.reviveSlot.RefreshSlot()
			self.reviveResultSlot.RefreshSlot()
			pet = GetPet(petId)
			age = pet.AgeSeconds(end or Now()) if pet else 0
			self.reviveAgeText.SetText(Days(age))
			self.reviveResultAgeText.SetText(Days(age * 8 / 10))
			self.__RefreshReviveCount()
			return True
		if self.reviveCell < 0:
			_Popup(T("REVIVE_EMPTY"))
			return False
		if cell in self.reviveCells:
			return False
		if self.__ReviveHave() >= self.__ReviveNeed():
			return False
		if slot < 0 or self.reviveCells[slot] >= 0:
			free = [i for i in xrange(REVIVE_SLOTS) if self.reviveCells[i] < 0]
			if not free:
				return False
			slot = free[0]
		count = player.GetItemCount(cell)
		self.reviveCells[slot] = cell
		self.reviveCounts[slot] = count
		self.reviveMaterialSlot.SetItemSlot(slot, vnum, count if count > 1 else 0)
		self.reviveMaterialSlot.RefreshSlot()
		self.__RefreshReviveCount()
		return True

