def AppendSkillToolTip(tt, petId, slot, skillId=0, level=0):
	"""The pet skill's tooltip (uitooltip.PetSkillToolTip too): name, kind, description, the value now and at the
	next level (player.GetPetSkillByIndex: the server's numbers for this pet), chance, duration, cooldown."""
	cool = 0
	if petId and not skillId:
		skillId, level, cool = GetSkill(petId, slot)
	if not skillId:
		return
	name, icon, kind, cooldown, unit, book, desc = SkillInfo(skillId)
	tt.SetTitle(name)
	tt.AppendTextLine(T("SKILL_KIND_AUTO") if kind == 2 else T("SKILL_KIND_PASSIVE"), tt.CONDITION_COLOR)
	tt.AppendDescription(desc, 26)
	trigger = T("SKILL_TRIGGER_%d" % skillId, "")
	if trigger:
		tt.AppendDescription(trigger, 26, tt.CONDITION_COLOR)
	if level:
		tt.AppendSpace(5)
		tt.AppendTextLine(T("SKILL_LEVEL") % (level, PD.SKILL_LEVEL_MAX), tt.TITLE_COLOR)
		for lv, label, color in ((level, "SKILL_CUR", tt.SPECIAL_POSITIVE_COLOR), (level + 1, "SKILL_NEXT", tt.NORMAL_COLOR)):
			if lv > PD.SKILL_LEVEL_MAX:
				continue
			chance, value, duration = _SkillByIndex(petId, slot, lv, skillId)
			if value:
				tt.AppendTextLine(T(label) % SkillValueText(skillId, value), color)
			if kind == 2 and chance:
				tt.AppendTextLine(T("SKILL_CHANCE") % chance, color)
			if duration and skillId != 17:
				tt.AppendTextLine(T("SKILL_DURATION") % Tenths(duration), color)
	if kind == 2 and cooldown:
		tt.AppendTextLine(T("SKILL_COOLDOWN") % Duration(cooldown), tt.NORMAL_COLOR)
		if cool and cool > Now():
			tt.AppendTextLine(T("SKILL_COOLDOWN_LEFT") % Duration(cool - Now()), tt.NEGATIVE_COLOR)
	if level and level < PD.SKILL_LEVEL_MAX:
		tt.AppendSpace(5)
		tt.AppendTextLine(T("SKILL_UPGRADE_HINT") % Money(PD.SKILL_UPGRADE_PRICE), tt.NORMAL_COLOR)


def _SkillByIndex(petId, slot, level, skillId):
	try:
		v = player.GetPetSkillByIndex(petId, slot, level)
		return int(v[0]), int(v[1]), int(v[2])
	except Exception:
		chance = 0
		if skillId in PD.ACTIVATE and 1 <= level <= len(PD.ACTIVATE[skillId]):
			chance = PD.ACTIVATE[skillId][level - 1]
		return chance, 0, 0


def _Question(text, accept, cancel=None, text2=None):
	"""A yes/no dialog; accept / cancel are called after it closes."""
	if text2 is None:
		dlg = uiCommon.QuestionDialog()
		dlg.SetText(text)
		try:
			dlg.SetWidth(max(dlg.GetWidth(), dlg.textLine.GetTextSize()[0] + 40))
		except Exception:
			pass
	else:
		dlg = uiCommon.QuestionDialog2()
		dlg.SetText1(text)
		dlg.SetText2(text2)
		try:
			w = max(dlg.textLine1.GetTextSize()[0], dlg.textLine2.GetTextSize()[0])
			dlg.SetWidth(max(dlg.GetWidth(), w + 40))
		except Exception:
			pass

	def onAccept():
		dlg.Close()
		_dialogs.discard(dlg)
		accept()

	def onCancel():
		dlg.Close()
		_dialogs.discard(dlg)
		if cancel:
			cancel()
	dlg.SetAcceptEvent(onAccept)
	dlg.SetCancelEvent(onCancel)
	dlg.Open()
	_dialogs.add(dlg)
	return dlg


_dialogs = set()


def _Popup(text):
	dlg = uiCommon.PopupDialog()
	dlg.SetText(text)
	try:
		dlg.SetWidth(max(dlg.GetWidth(), dlg.textLine.GetTextSize()[0] + 40))
	except Exception:
		pass

	def onClose():
		_dialogs.discard(dlg)
	try:
		dlg.SetAcceptEvent(onClose)
	except Exception:
		pass
	dlg.Open()
	_dialogs.add(dlg)


def _CloseDialogs():
	for dlg in list(_dialogs):
		try:
			dlg.Close()
		except Exception:
			pass
	_dialogs.clear()


def _SetExpBalls(balls, mobCur, mobMax, itemCur, itemMax):
	"""4 red balls (the mob EXP, 90 % of the level), 1 blue (the item EXP, 10 %): each fills from the bottom."""
	mobCur = max(0, min(mobCur, mobMax))
	itemCur = max(0, min(itemCur, itemMax))
	quarter = mobMax / MOB_EXP_BALLS
	full = min(MOB_EXP_BALLS, mobCur / quarter) if quarter else 0
	for ball in balls:
		ball.Hide()
	for i in xrange(full):
		balls[i].SetRenderingRect(0.0, 0.0, 0.0, 0.0)
		balls[i].Show()
	if quarter and full < MOB_EXP_BALLS:
		balls[full].SetRenderingRect(0.0, float(mobCur % quarter) / quarter - 1.0, 0.0, 0.0)
		balls[full].Show()
	if itemMax:
		balls[MOB_EXP_BALLS].SetRenderingRect(0.0, float(itemCur) / float(itemMax) - 1.0, 0.0, 0.0)
		balls[MOB_EXP_BALLS].Show()


def _ExpLines(mobCur, mobMax, itemCur, itemMax):
	total = mobMax + itemMax
	pct = (float(min(mobCur, mobMax) + min(itemCur, itemMax)) / total * 100.0) if total else 0.0
	lines = [T("EXP_MOB") % (Money(mobCur), Money(mobMax)), T("EXP_ITEM") % (Money(itemCur), Money(itemMax)),
		T("EXP_TOTAL") % pct]
	if total and mobCur >= mobMax and itemCur >= itemMax:
		lines.append(T("EXP_FULL"))
	return lines


