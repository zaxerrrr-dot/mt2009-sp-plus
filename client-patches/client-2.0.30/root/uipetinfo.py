# the inventory's hooks (uiinventory.py)
def UseBagItem(cell, vnum):
	"""uiinventory __UseItem: an egg opens the hatching window, Reverti Zwierza asks and removes every skill.
	True when the use was handled here (no item use packet)."""
	if not IsEnabled():
		return False
	t, sub = ItemKind(vnum)
	if t != ITEM_TYPE_GROWTH_PET:
		return False
	if sub == PET_EGG:
		if not CanUsePetItem():
			return True
		wnd = GetWindow()
		if wnd:
			wnd.wndHatching.Open(player.INVENTORY, cell)
		return True
	if sub == PET_SKILL_ALL_DEL_BOOK:
		if not IsWindowOpen():
			Chat(T("NEED_WINDOW_FOR_REVERTI"))
			return True
		if not ActivePetId():
			_Popup(T("NEED_SUMMON"))
			return True
		_Question(T("SKILL_DEL_ALL_Q"), lambda: net.SendPetDeleteAllSkill(player.INVENTORY, cell))
		return True
	if sub == PET_SKILL:
		Chat(T("SKILL_BOOK_HINT"))
		if not IsWindowOpen():
			ToggleWindow()
		return True
	return False


def CanUsePetItem():
	"""net.CheckUsePetItem: no egg while trading, a shop, the mall or the safebox is open."""
	try:
		result = net.CheckUsePetItem()
	except Exception:
		return True
	if result != getattr(item, "PET_EGG_USE_TRUE", result):
		Chat(T("WINDOW_BUSY"))
		return False
	return True


def TakeInventoryItem(cell):
	"""uiinventory UseItemSlot (a right click): with a pet window open the item goes into it. True when taken."""
	if not IsEnabled() or not _wnd:
		return False
	try:
		return bool(_wnd.TakeBagItem(cell))
	except Exception:
		import dbg
		import sys
		dbg.TraceError("uipetinfo.TakeInventoryItem: %s %s" % (sys.exc_info()[0], sys.exc_info()[1]))
		return False


def DropOnItem(srcVnum, srcCell, dstCell):
	"""uiinventory __DropSrcItemToDestItemInInventory: "use" - send the item-to-item use (Odzywka onto a seal, a
	seal onto Klatka Transportowa), "done" - handled here (Pergamin Nazwy opens the rename window), None - not ours."""
	if not IsEnabled():
		return None
	dstVnum = player.GetItemIndex(dstCell)
	ts, ss = ItemKind(srcVnum)
	td, sd = ItemKind(dstVnum)
	if ts != ITEM_TYPE_GROWTH_PET and td != ITEM_TYPE_GROWTH_PET:
		return None
	if ts == ITEM_TYPE_GROWTH_PET and td == ITEM_TYPE_GROWTH_PET:
		if ss == PET_NAME_CHANGE and sd == PET_UPBRINGING:
			wnd = GetWindow()
			if wnd:
				if CanUsePetItem():
					wnd.wndNameChange.Open(srcCell, dstCell)
			return "done"
		if ss in (PET_FEEDSTUFF, PET_PRIMIUM_FEEDSTUFF) and sd == PET_UPBRINGING:
			return "use"
		if ss == PET_UPBRINGING and sd == PET_BAG:
			return "use"
	return None


def IsUsableOnItem(srcVnum):
	"""uiinventory __IsUsableItemToItem: the pet items that are dropped on another item."""
	t, s = ItemKind(srcVnum)
	return t == ITEM_TYPE_GROWTH_PET and s in (PET_NAME_CHANGE, PET_FEEDSTUFF, PET_UPBRINGING)


def CanUseOnItem(srcVnum, dstCell):
	"""uiinventory __CanUseSrcItemToDstItem: the targets DropOnItem acts on (no side effect here)."""
	if not IsEnabled():
		return False
	ts, ss = ItemKind(srcVnum)
	td, sd = ItemKind(player.GetItemIndex(dstCell))
	if ts != ITEM_TYPE_GROWTH_PET or td != ITEM_TYPE_GROWTH_PET:
		return False
	return (ss in (PET_NAME_CHANGE, PET_FEEDSTUFF, PET_PRIMIUM_FEEDSTUFF) and sd == PET_UPBRINGING) or \
		(ss == PET_UPBRINGING and sd == PET_BAG)


