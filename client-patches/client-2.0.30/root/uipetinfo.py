def EvolutionCheck(pet):
	"""(target stage or 0, the reason it cannot evolve or None)."""
	if not pet:
		return 0, T("NEED_SUMMON")
	stage = pet.evolution
	target = stage + 1
	if target not in PD.EVOLUTION:
		return 0, T("EVOL_MAX")
	level = PD.EVOLUTION[target][0]	# MT2009_PLUS_PET_EVOL_NO_AGE_V1: no age requirement (the old wiki's 30 days)
	if target == 6:
		if pet.championLevel < level:
			return target, T("EVOL_NEED_CHAMPION") % level
		if not pet.ExpFull(True):
			return target, T("EVOL_NEED_EXP")
	else:
		if pet.level < level:
			return target, T("EVOL_NEED_LEVEL") % level
		if target != 4 and not pet.ExpFull(False):
			return target, T("EVOL_NEED_EXP")
	return target, None


def MissingMaterials(target):
	if target not in PD.EVOLUTION:
		return []
	return [(vnum, need, CountItem(vnum)) for (vnum, need) in PD.EVOLUTION[target][2] if CountItem(vnum) < need]


