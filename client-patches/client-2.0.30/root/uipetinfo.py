def Money(n):
	s = "%d" % max(0, int(n))
	out = []
	while len(s) > 3:
		out.insert(0, s[-3:])
		s = s[:-3]
	out.insert(0, s)
	return ".".join(out)


def Tenths(v):
	v = int(v)
	if v % 10:
		return "%d.%d" % (v / 10, abs(v) % 10)
	return "%d" % (v / 10)


def Pct1(v001):
	"""0.001 % units -> '1.5' for 1555: one decimal, cut (not rounded) - the hidden decimals count but show only when
	they make a whole tenth (wiki: 1.599 % shows 1.5, 1.600 % 1.6)."""
	v001 = max(0, int(v001))
	return "%d.%d" % (v001 / 1000, (v001 % 1000) / 100)


def Duration(seconds):
	seconds = max(0, int(seconds))
	d, rest = divmod(seconds, DAY)
	h, rest = divmod(rest, 3600)
	m = rest / 60
	if d:
		return (T("TIME_D") % d) + ((" " + T("TIME_H") % h) if h else "")
	if h:
		return (T("TIME_H") % h) + ((" " + T("TIME_M") % m) if m else "")
	if m:
		return T("TIME_M") % m
	return T("TIME_S") % seconds


def Days(seconds):
	n = max(0, int(seconds)) / DAY
	if n == 1:
		return T("DAY_ONE")
	return T("DAYS") % n


