# the module's interface (interfacemodule.py, game.py, uiinventory.py, uitooltip.py)
def Create(interface):
	"""interfacemodule.MakeInterface: remembers the interface (its inventory and item tooltip); the windows are made
	when first needed."""
	global _interface
	Destroy()
	try:
		_interface = _proxy(interface)
	except TypeError:
		_interface = interface


def Destroy():
	global _interface, _wnd, _mini, _applied, _appliedPage
	_CloseDialogs()
	HideSkillToolTip()
	if _wnd:
		_wnd.Destroy()
	if _mini:
		_mini.Destroy()
	_wnd = None
	_mini = None
	_locks.clear()
	_applied = set()
	_appliedPage = -1
	_interface = None


def GetWindow():
	global _wnd
	if not IsEnabled():
		return None
	if _wnd is None:
		_wnd = PetInformationWindow()
	return _wnd


def ToggleWindow():
	wnd = GetWindow()
	if not wnd:
		return
	if wnd.IsShow():
		wnd.Close()
	else:
		wnd.Open()


def IsWindowOpen():
	return bool(_wnd and _wnd.IsShow())


def CloseWindow():
	if _wnd:
		_wnd.Close()


def OnUpdate():
	"""game.py OnUpdate: the small window while a pet is summoned, the bag slots locked by the pet windows."""
	global _mini, _nextMini
	if not IsEnabled() or _interface is None:
		return
	if _locks or _applied:
		_ApplyLocks()
	if app.GetTime() < _nextMini:
		return
	_nextMini = app.GetTime() + MINI_REFRESH_SECONDS
	pet = ActivePet()
	if not pet:
		if _mini and _mini.IsShow():
			_mini.Hide()
		return
	iface = _Interface()
	try:
		uiShown = iface.wndTaskBar.IsShow() if iface and getattr(iface, "wndTaskBar", None) else True
	except Exception:
		uiShown = True
	if _mini is None:
		_mini = PetMiniInformationWindow()
	flags = FlashFlags(pet)
	_mini.Refresh(pet, flags[0] or flags[1] or flags[2])
	if uiShown and not _mini.IsShow():
		_mini.Show()
	elif not uiShown and _mini.IsShow():
		_mini.Hide()


def RefreshAll(*args):
	global _nextMini
	_nextMini = 0.0
	if _wnd and _wnd.IsShow():
		_wnd.nextRefresh = 0.0
		if _wnd.wndPotential and _wnd.wndPotential.IsShow():
			_wnd.wndPotential.nextRefresh = 0.0


