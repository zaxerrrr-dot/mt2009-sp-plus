#!/usr/bin/env python3
"""Write playerbot_i18n_codepages.h: the Windows code pages the clients may
read, as tables the game core needs to turn the UTF-8 catalogs into a
client's bytes and to fold a client's line for matching.

For every code page: the Unicode of bytes 0x80-0xFF (0 = unused), and the
"fold" of each byte - its base letter in lowercase ASCII when it is a Latin
letter with a mark (e -> e, sz -> s), the lowercase byte of the same page for a
letter of another script (Greek, Cyrillic, Arabic), a space otherwise.
"""
import os, unicodedata

PAGES = [1250, 1251, 1252, 1253, 1254, 1256]
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'linux-port/overlays/playerbot/src/game/src/playerbot_i18n_codepages.h')
SPECIAL = {'ß': 's', 'ł': 'l', 'Ł': 'l', 'đ': 'd', 'Đ': 'd', 'ı': 'i',
           'ø': 'o', 'Ø': 'o', 'æ': 'a', 'Æ': 'a', 'œ': 'o', 'Œ': 'o'}


def fold(ch, page):
    if ch is None:
        return 0x20
    if ch in SPECIAL:
        return ord(SPECIAL[ch])
    base = unicodedata.normalize('NFKD', ch)[0]
    if 'a' <= base.lower() <= 'z' and base.isascii():
        return ord(base.lower())
    if ch.isalpha():
        lo = ch.lower()
        try:
            b = lo.encode('cp%d' % page)
            if len(b) == 1:
                return b[0]
        except UnicodeEncodeError:
            pass
        return ord(ch.encode('cp%d' % page))
    return 0x20


def main():
    lines = ['#ifndef __INC_METIN2_PLAYERBOT_I18N_CODEPAGES_H__', '#define __INC_METIN2_PLAYERBOT_I18N_CODEPAGES_H__', '',
             '// Generated by tools/playerbot_i18n/gen_codepages.py - do not edit.', '',
             'namespace playerbot_i18n_cp', '{',
             '\tstruct TCodePage', '\t{', '\t\tint id;', '\t\tunsigned short uni[128];   // bytes 0x80-0xFF, 0 unused',
             '\t\tunsigned char fold[128];   // the byte folded for matching', '\t};', '',
             '\tstatic const TCodePage kPages[] = {']
    for p in PAGES:
        uni, fo = [], []
        for b in range(0x80, 0x100):
            try:
                ch = bytes([b]).decode('cp%d' % p)
            except UnicodeDecodeError:
                ch = None
            uni.append(0 if ch is None else ord(ch))
            fo.append(fold(ch, p))
        lines.append('\t\t{ %d,' % p)
        lines.append('\t\t\t{ ' + ', '.join(str(u) for u in uni) + ' },')
        lines.append('\t\t\t{ ' + ', '.join(str(f) for f in fo) + ' } },')
    lines += ['\t};', '\tstatic const int kPageCount = (int)(sizeof(kPages) / sizeof(kPages[0]));', '}', '', '#endif', '']
    with open(OUT, 'w', newline='\n') as fp:
        fp.write('\n'.join(lines))
    print('wrote', os.path.normpath(OUT))


if __name__ == '__main__':
    main()
