#!/usr/bin/env python3
"""gen_dropknow_places.py - MT2009_PLUS_BOT_DROPKNOW_V1: where the Yohara monsters live, for the bots' drop knowledge
(linux-port/overlays/playerbot/src/game/src/playerbot_dropknow_places.h).

The drop wiki (cmd_general.cpp) reads every map's regen/boss/stone.txt and the dungeons' regen files of drop_wiki.txt -
the Yohara dungeons spawn most of their monsters from their quests, which it does not read. The Yohara builders
already list every vnum each map shows (the spawn files with their groups unfolded + the quests' spawns + the summons):
linux-port/docker/game/yohara_*/spawned.txt, "<map index> <vnum>" a line. This joins them into one sorted table.

Run from the repository root:  python3 tools/dropknow/gen_dropknow_places.py
"""
import glob
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
OUT = os.path.join(ROOT, "linux-port/overlays/playerbot/src/game/src/playerbot_dropknow_places.h")


def main():
    pairs = set()
    sources = sorted(glob.glob(os.path.join(ROOT, "linux-port/docker/game/yohara_*/spawned.txt")))
    for path in sources:
        for line in open(path, encoding="latin-1"):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            words = line.split()
            if len(words) < 2 or not words[0].isdigit() or not words[1].isdigit():
                continue
            pairs.add((int(words[0]), int(words[1])))
    if not pairs:
        sys.exit("gen_dropknow_places: no spawned.txt rows found")
    rows = sorted(pairs)
    out = []
    out.append("#ifndef __INC_METIN2_PLAYERBOT_DROPKNOW_PLACES_H__")
    out.append("#define __INC_METIN2_PLAYERBOT_DROPKNOW_PLACES_H__")
    out.append("")
    out.append("// MT2009_PLUS_BOT_DROPKNOW_V1: every vnum each Yohara map shows (map index, vnum) - GENERATED by")
    out.append("// tools/dropknow/gen_dropknow_places.py from linux-port/docker/game/yohara_*/spawned.txt (%d files); do not edit." % len(sources))
    out.append("")
    out.append("namespace")
    out.append("{")
    out.append("\tconst long PLAYERBOT_DROPKNOW_PLACES[][2] = {")
    line = "\t\t"
    for m, v in rows:
        cell = "{ %d, %d }, " % (m, v)
        if len(line) + len(cell) > 118:
            out.append(line.rstrip())
            line = "\t\t"
        line += cell
    if line.strip():
        out.append(line.rstrip())
    out.append("\t};")
    out.append("\tconst int PLAYERBOT_DROPKNOW_PLACE_COUNT = (int)(sizeof(PLAYERBOT_DROPKNOW_PLACES) / sizeof(PLAYERBOT_DROPKNOW_PLACES[0]));")
    out.append("}")
    out.append("")
    out.append("#endif")
    open(OUT, "w", newline="\n").write("\n".join(out) + "\n")
    print("gen_dropknow_places: %d rows from %d files -> %s" % (len(rows), len(sources), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
