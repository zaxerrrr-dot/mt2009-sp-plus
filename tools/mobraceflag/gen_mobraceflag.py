# -*- coding: utf-8 -*-
"""MT2009_PLUS_YOHARA_RASY_V1: writes client-2.0.30/root/mobraceflag.py (MT2009_PLUS_TARGET_BONUS_V1, Autor: Vekirion) -
the race flags (setRaceFlag bits 0-10) the target bar's "Silny przeciwko: ..." names, by vnum.

The table was written once by hand (before Yohara) and never again: every monster added since (Yohara, Zaklety Las,
the PB / SZC dungeons, Atlantis, Zodiac ...) had no row, so the bar named no race bonus on them (the owner, 10 November
2026: "w Zakletym Lesie nie dziala bonus silny przeciwko diablom" - the server gave it, the bar did not show it).

Now: every MONSTER / STONE row of the world's mob_proto (race 0 too - a vnum of the table is the server's word) and
every other row with a race, then
the race UPDATEs of the generators' files (linux-port/docker/mariadb/playerbot/*.sql, "& ~2047) | N WHERE vnum IN"),
so a race fixed in the repo is in the table before the database has it. A vnum the table does not know (a monster
added later) falls back to the client's own mob_proto (nonplayer.GetMonsterRaceFlag) in mobraceflag.Get.

  python3 tools/mobraceflag/gen_mobraceflag.py [--container mt2009plustest-db] [--tsv vnum_type_race.tsv]
"""
import argparse
import glob
import os
import re
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(REPO, 'client-patches', 'client-2.0.30', 'root', 'mobraceflag.py')
SQL_DIR = os.path.join(REPO, 'linux-port', 'docker', 'mariadb', 'playerbot')
RACE_BITS = 2047
QUERY = 'SELECT vnum, type, (setRaceFlag + 0) & %d FROM world.mob_proto ORDER BY vnum' % RACE_BITS
RACE_UPDATE = re.compile(r'UPDATE world\.mob_proto SET setRaceFlag = \(\(setRaceFlag \+ 0\) & ~%d\) \| (\d+) '
                         r'WHERE vnum IN \(([\d,]+)\)' % RACE_BITS)

HEAD = '''# MT2009_PLUS_TARGET_BONUS_V1 (Autor: Vekirion)
# Race flags of the monsters (mob_proto setRaceFlag, bits 0-10 =
# RACE_FLAG_ANIMAL..RACE_FLAG_TREE of common/length.h), by vnum, so
# uitarget.py names the bonuses that hit the target (battle.cpp
# CalcAttBonus). The server's word: every MONSTER / STONE row of
# world.mob_proto (race 0 too), every other raced row, plus the repo's
# race fixes.
# GENERATED by tools/mobraceflag/gen_mobraceflag.py (MT2009_PLUS_YOHARA_RASY_V1)
# - do not edit, rerun it after mob_proto race flags change. A vnum not
# here (a monster added later) takes the race of the client's own
# mob_proto (nonplayer.GetMonsterRaceFlag).

ANIMAL	= 1 << 0
UNDEAD	= 1 << 1
DEVIL	= 1 << 2
HUMAN	= 1 << 3
ORC		= 1 << 4
MILGYO	= 1 << 5
INSECT	= 1 << 6
FIRE	= 1 << 7
ICE		= 1 << 8
DESERT	= 1 << 9
TREE	= 1 << 10

RACE_BITS = (1 << 11) - 1

RACE_FLAGS = {
'''

TAIL = '''}

def Get(vnum):
	flag = RACE_FLAGS.get(vnum)
	if flag is not None:
		return flag
	try:
		import nonplayer
		return nonplayer.GetMonsterRaceFlag(vnum) & RACE_BITS
	except Exception:
		return 0
'''


def from_db(container):
    cmd = ['docker', 'exec', container, 'sh', '-c',
           'mariadb -uroot -p"$MARIADB_ROOT_PASSWORD" -N -B -e "%s"' % QUERY]
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--container', default='mt2009plustest-db')
    ap.add_argument('--tsv', help='vnum<TAB>type<TAB>race rows instead of the database')
    a = ap.parse_args()
    text = open(a.tsv).read() if a.tsv else from_db(a.container)
    races = {}
    for line in text.splitlines():
        p = line.split('\t')
        if len(p) == 3 and p[0].isdigit() and (p[1] in ('0', '2') or p[2] != '0'):   # MONSTER, STONE; any raced
            races[int(p[0])] = int(p[2])
    assert len(races) > 1000, len(races)
    fixed = 0
    for path in sorted(glob.glob(os.path.join(SQL_DIR, '*.sql'))):
        for bits, vnums in RACE_UPDATE.findall(open(path, encoding='utf-8', errors='replace').read()):
            for v in map(int, vnums.split(',')):
                if v in races and races[v] != int(bits):
                    fixed += 1
                races[v] = int(bits)
    with open(OUT, 'w', newline='\n') as f:
        f.write(HEAD)
        f.write(''.join('\t%d: %d,\n' % (v, races[v]) for v in sorted(races)))
        f.write(TAIL)
    print('mobraceflag.py: %d vnums (%d with a race), %d set by the repo\'s race fixes' % (
        len(races), sum(1 for r in races.values() if r), fixed))


if __name__ == '__main__':
    main()
