#!/usr/bin/env python3
"""gen_rznm_regen.py <owsap share/data/dungeon> <flame grid.bin> <snow grid.bin> <out data/dungeon>

MT2009_PLUS_RZNM_OFFICIAL_V2 (the owner, 15 October: the full official density in Razador's and
Nemere's rooms): the two dungeons' regen files from Owsap v6.2.6's flame_dungeon / snow_dungeon
(= the official ones) - every spawn line, not every fourth (MT2009_PLUS_DUNGEONS_V1's level-55 cut).

    razador_mt/fd_a..fd_f.txt, fd_boss.txt   <- flame_dungeon/fd_a..fd_f.txt, fd_fild_boss.txt
    nemere_mt/zone_N.txt (N = 1..10)          <- snow_dungeon/sd_N.txt

The lines stay Owsap's ("r" with the groups of groups 6001-6003 for the fire rooms, "ga" with the
groups 6051-6059 for the ice floors - both the same in our share). A spawn point standing on a
blocked cell of OUR server_attr (metin2_map_n_flame/snow_dungeon_01, made from the GF client's
attr.atr) is moved to the nearest open cell (the 50-unit grid's ATTR_BLOCK|ATTR_OBJECT; at most
MAX_SNAP cells). The grids are tools/arezzo_bot_map.py decode's output (python-lzo, m2pack-lzo image):

    docker run --rm -v REPO:/r -v OUT:/s m2pack-lzo python3 /r/tools/arezzo_bot_map.py decode \
        /r/linux-port/docker/game/dungeons/map/metin2_map_n_flame_dungeon_01/server_attr /s/flame.grid
"""
import os
import struct
import sys

BLOCK = 0x81
MAX_SNAP = 12
FLAME = [('fd_a.txt', 'fd_a.txt'), ('fd_b.txt', 'fd_b.txt'), ('fd_c.txt', 'fd_c.txt'), ('fd_d.txt', 'fd_d.txt'),
         ('fd_e.txt', 'fd_e.txt'), ('fd_f.txt', 'fd_f.txt'), ('fd_fild_boss.txt', 'fd_boss.txt')]
SNOW = [('sd_%d.txt' % n, 'zone_%d.txt' % n) for n in range(1, 11)]


class Grid:
    def __init__(self, path):
        g = open(path, 'rb').read()
        self.w, self.h = struct.unpack_from('<ii', g, 0)
        self.g = g[8:]

    def free(self, x, y):
        # a regen cell (100 units) is open when its four 50-unit cells are
        for dy in (0, 1):
            for dx in (0, 1):
                cx, cy = x * 2 + dx, y * 2 + dy
                if not (0 <= cx < self.w and 0 <= cy < self.h) or self.g[cy * self.w + cx] & BLOCK:
                    return False
        return True

    def snap(self, x, y):
        if self.free(x, y):
            return x, y, 0
        for r in range(1, MAX_SNAP + 1):
            best = None
            for dy in range(-r, r + 1):
                for dx in range(-r, r + 1):
                    if max(abs(dx), abs(dy)) != r or not self.free(x + dx, y + dy):
                        continue
                    d = dx * dx + dy * dy
                    if best is None or d < best[0]:
                        best = (d, x + dx, y + dy)
            if best:
                return best[1], best[2], r
        raise SystemExit('no open cell within %d of (%d, %d)' % (MAX_SNAP, x, y))


def convert(src, dst, grid, note):
    out = ['// ' + note]
    moved = n = 0
    for line in open(src, encoding='latin-1'):
        p = line.rstrip('\r\n').split('\t')
        if len(p) < 11 or p[0] not in ('r', 'g', 'ga', 'm', 'ma'):
            continue
        x, y, r = grid.snap(int(p[1]), int(p[2]))
        if r:
            moved += 1
            print('  %s: (%s, %s) -> (%d, %d), %d cells' % (os.path.basename(dst), p[1], p[2], x, y, r))
        p[1], p[2] = str(x), str(y)
        out.append('\t'.join(p))
        n += 1
    with open(dst, 'w', encoding='latin-1', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('%s: %d lines (%d moved)' % (dst, n, moved))


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    src, flame, snow, out = sys.argv[1:]
    fg, sg = Grid(flame), Grid(snow)
    for a, b in FLAME:
        convert(os.path.join(src, 'flame_dungeon', a), os.path.join(out, 'razador_mt', b), fg,
                'MT2009_PLUS_RZNM_OFFICIAL_V2 (razador): Owsap v6.2.6 flame_dungeon/%s, every line (the official '
                'density); points on a blocked cell of our server_attr moved to the nearest open one. '
                'GENERATED by tools/rznm/gen_rznm_regen.py' % a)
    for a, b in SNOW:
        convert(os.path.join(src, 'snow_dungeon', a), os.path.join(out, 'nemere_mt', b), sg,
                'MT2009_PLUS_RZNM_OFFICIAL_V2 (nemere): Owsap v6.2.6 snow_dungeon/%s, every line (the official '
                'density, the groups 6051-6059 of group.txt); points on a blocked cell of our server_attr moved '
                'to the nearest open one. GENERATED by tools/rznm/gen_rznm_regen.py' % a)


if __name__ == '__main__':
    main()
