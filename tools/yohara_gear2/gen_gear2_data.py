#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_gear2_data.py

MT2009_PLUS_BOT_YOHARA_GEAR2_V1 (the owner, 22 October 2026, items 21 and 23 of cache/yohara/boty-yohara-lista.md):
the recipes the bots craft their level-100 helmets and level-90..115 body armours by, read from the files the players'
windows are made of, so a change there is a change for the bots after a run of this script:

  linux-port/docker/game/cube.helm100.txt   Straznik Smokow Jaharr (20421, Yongan / Joan / Pyungmoo): a level-80
                                            helmet +5..+9 -> a level-100 helmet +0 (tools/yhelm100) - 40 recipes,
                                            the Dragona ones keep the helmet on a failure (fail_keep)
  linux-port/docker/game/cube.zbroje105.txt Kawuco (20413, Przyladek Smoczego Ognia): a level-90 armour +5..+9 + Plan
                                            Zbroi + a dye + 5 plates -> a level-105 armour +0 (tools/zbroje105)
  linux-port/docker/game/quest/angmur.quest Admiral Angmur (20378 on the cape, 20812 in Opuszczona Twierdza): a
                                            level-66 armour +9 -> 90, a level-90 armour +9 -> 105 (the white or the
                                            black one), always, the bonuses and stones kept
Seon-Pyeong's step (+9 -> the cyanite ones, refine 39903) is the engine's refine table - the bots read it there.

Writes (GENERATED - do not edit, run this again):
  linux-port/overlays/playerbot/src/game/src/playerbot_yohara_gear2_data.h

Example: python3 tools/yohara_gear2/gen_gear2_data.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
GAME = os.path.join(REPO, 'linux-port', 'docker', 'game')
OUT = os.path.join(REPO, 'linux-port', 'overlays', 'playerbot', 'src', 'game', 'src', 'playerbot_yohara_gear2_data.h')
NPC_KIND = {20421: 'PLAYERBOT_GEAR2_NPC_JAHARR', 20413: 'PLAYERBOT_GEAR2_NPC_KAWUCO'}
MAX_MATS = 5


def cube(path, npcs):
    """[(npc, input, input count, mats[(vnum, count)], reward, gold, percent, fail_keep, comment)]"""
    out, cur, comment = [], None, ''
    for line in open(path, encoding='utf-8', errors='replace'):
        s = line.strip()
        if s.startswith('#'):
            comment = s.lstrip('# ').strip()
            continue
        p = s.split()
        if not p:
            continue
        if p[0] == 'section':
            cur = dict(npc=0, items=[], reward=0, gold=0, percent=0, keep=0, comment=comment)
        elif cur is None:
            continue
        elif p[0] == 'npc':
            cur['npc'] = int(p[1])
        elif p[0] == 'item':
            cur['items'].append((int(p[1]), int(p[2])))
        elif p[0] == 'reward':
            cur['reward'] = int(p[1])
        elif p[0] == 'gold':
            cur['gold'] = int(p[1])
        elif p[0] == 'percent':
            cur['percent'] = int(p[1])
        elif p[0] == 'fail_keep':
            cur['keep'] = 1
        elif p[0] == 'end':
            if cur['npc'] in npcs:
                assert cur['items'][0][1] == 1 and len(cur['items']) - 1 <= MAX_MATS, cur
                out.append(cur)
            cur = None
    return out


def angmur(path):
    t = open(path, encoding='cp1250', errors='replace').read()
    mats = {}
    for name in ('m90', 'white', 'black'):
        m = re.search(r'local %s = \{(.*?)\}\s*\n' % name, t)
        mats[name] = [(int(a), int(b)) for a, b in re.findall(r'\{(\d+),\s*(\d+)\}', m.group(1))]
    out = []
    for src, body in re.findall(r'\[(\d+)\]\s*=\s*\{(.*?)\},\s*\n', t):
        for reward, mname, gold in re.findall(r'\{(\d+),\s*(\w+),\s*(\d+)\}', body):
            out.append(dict(npc=20378, items=[(int(src), 1)] + mats[mname], reward=int(reward), gold=int(gold),
                            percent=100, keep=1, comment='Angmur %s: %s -> %s' % (mname, src, reward)))
    assert len(out) == 12, len(out)
    return out


def row(r, kind, keeps_bonus):
    mats = r['items'][1:]
    mats += [(0, 0)] * (MAX_MATS - len(mats))
    return '\t\t{ %s, %5d, %5d, %9dLL, %3d, %d, %d, { %s } },\t// %s' % (
        kind, r['items'][0][0], r['reward'], r['gold'], r['percent'], r['keep'], keeps_bonus,
        ', '.join('{ %d, %d }' % m for m in mats), r['comment'].encode('ascii', 'replace').decode('ascii'))


def main():
    helm = cube(os.path.join(GAME, 'cube.helm100.txt'), (20421,))
    kawuco = cube(os.path.join(GAME, 'cube.zbroje105.txt'), (20413,))
    ang = angmur(os.path.join(GAME, 'quest', 'angmur.quest'))
    assert len(helm) == 40 and len(kawuco) == 80, (len(helm), len(kawuco))
    L = ['// playerbot_yohara_gear2_data.h - GENERATED by tools/yohara_gear2/gen_gear2_data.py from cube.helm100.txt,',
         '// cube.zbroje105.txt and quest/angmur.quest - do not edit, run the generator. MT2009_PLUS_BOT_YOHARA_GEAR2_V1:',
         '// the recipes of Jaharr (level-100 helmets), Kawuco and Admiral Angmur (body armours 90 / 105) the bots craft',
         '// by (playerbot_yohara_gear2.h). Per row: the NPC, the piece given (its exact vnum, the plus in it), the reward,',
         '// the Yang, the chance, whether a failure keeps the piece (Jaharr\'s Dragona helmets; Angmur: always made),',
         '// whether the bonuses and stones go over to the reward (Angmur), the materials.',
         '#ifndef __INC_METIN2_PLAYERBOT_YOHARA_GEAR2_DATA_H__',
         '#define __INC_METIN2_PLAYERBOT_YOHARA_GEAR2_DATA_H__',
         '',
         'namespace',
         '{',
         '\tenum',
         '\t{',
         '\t\tPLAYERBOT_GEAR2_NPC_JAHARR,',
         '\t\tPLAYERBOT_GEAR2_NPC_KAWUCO,',
         '\t\tPLAYERBOT_GEAR2_NPC_ANGMUR,',
         '\t\tPLAYERBOT_GEAR2_NPC_SEONPYEONG,	// the elite refine (no row here: the engine\'s refine table)',
         '\t\tPLAYERBOT_GEAR2_NPC_COUNT,',
         '\t};',
         '',
         '\tstruct TPlayerBotGear2Recipe',
         '\t{',
         '\t\tBYTE bNpc;	// PLAYERBOT_GEAR2_NPC_*',
         '\t\tDWORD dwInput;',
         '\t\tDWORD dwReward;',
         '\t\tlong long llGold;',
         '\t\tBYTE bPercent;',
         '\t\tBYTE bFailKeep;',
         '\t\tBYTE bKeepBonus;',
         '\t\tstruct { DWORD vnum; WORD count; } mats[%d];' % MAX_MATS,
         '\t};',
         '',
         '\tconst TPlayerBotGear2Recipe PLAYERBOT_GEAR2_RECIPES[] = {']
    for r in helm:
        L.append(row(r, NPC_KIND[20421], 0))
    for r in kawuco:
        L.append(row(r, NPC_KIND[20413], 0))
    for r in ang:
        L.append(row(r, 'PLAYERBOT_GEAR2_NPC_ANGMUR', 1))
    L += ['\t};',
          '\tconst int PLAYERBOT_GEAR2_RECIPE_COUNT = sizeof(PLAYERBOT_GEAR2_RECIPES) / sizeof(PLAYERBOT_GEAR2_RECIPES[0]);',
          '}', '', '#endif', '']
    with open(OUT, 'w', encoding='ascii', newline='\n') as f:
        f.write('\n'.join(L))
    print('%s: %d recipes (Jaharr %d, Kawuco %d, Angmur %d)' % (os.path.relpath(OUT, REPO), len(helm) + len(kawuco) + len(ang),
                                                               len(helm), len(kawuco), len(ang)))


if __name__ == '__main__':
    main()
