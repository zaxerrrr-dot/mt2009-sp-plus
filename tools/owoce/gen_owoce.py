#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_owoce.py [--check]

MT2009_PLUS_RANK_FRUIT_CRAFT_V1 - the rank fruits crafted at Uriel (Yohara). The owner, 6 November 2026: "Dodaj
mozliwosc wytwarzania u Uriela. 7 owocow klasy poprzedniej przerabiasz na owoc wyzej. Czyli 7 jablek na 1 gruszke,
szansa 95%, bez oplaty yang."

  7 Jablko (80050)    -> 1 Gruszka (80051)
  7 Gruszka (80051)   -> 1 Winogrono (80052)
  7 Winogrono (80052) -> 1 Arbuz (80053)
  7 Arbuz (80053)     -> 1 Ananas (80054)
  95%, 0 Yang, no Gaya - Uriel (20011), his crafting window (MT2009_PLUS_NPC_CRAFT_WINDOW_V1: the server sends the
  list - "cube r_info" / "cube m_info" -, the client holds no recipe data); the window opens by quest mikstury_okno
  ("Wytwarzanie owocow").

The bots craft by the same numbers (playerbot_rank_points.h PLAYERBOT_FRUIT_CRAFT_*; playerbot_rank_fruit_craft.h) -
a change here is a change there (--check compares them).

Writes (GENERATED - edit this file, run it again):
  linux-port/docker/game/cube.owoce.txt     the 4 recipes - appended to cube.txt by game/Dockerfile

Example: python3 tools/owoce/gen_owoce.py          (write, then check)
         python3 tools/owoce/gen_owoce.py --check  (check only)
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
MARK = 'MT2009_PLUS_RANK_FRUIT_CRAFT_V1'
CUBE_OUT = os.path.join(REPO, 'linux-port', 'docker', 'game', 'cube.owoce.txt')
BOT_H = os.path.join(REPO, 'linux-port', 'overlays', 'playerbot', 'src', 'game', 'src', 'playerbot_rank_points.h')

URIEL = 20011
IN = 7
PCT = 95
GOLD = 0
FRUITS = [(80050, 'Jablko'), (80051, 'Gruszka'), (80052, 'Winogrono'), (80053, 'Arbuz'), (80054, 'Ananas')]


def render():
    out = ['# %s: the rank fruits at Uriel (%d) - the owner, 6 November 2026 (Yohara): seven of a fruit make one of the'
           % (MARK, URIEL),
           '# next, %d%%, no Yang. GENERATED by tools/owoce/gen_owoce.py. Appended to cube.txt by the game Dockerfile'
           % PCT,
           "# after cube.runy.txt; Uriel's window opens by quest mikstury_okno (\"Wytwarzanie owocow\").",
           '']
    for (low, lname), (high, hname) in zip(FRUITS, FRUITS[1:]):
        out += ['# %s <- %dx %s (Uriel)' % (hname, IN, lname),
                'section',
                'npc\t%d' % URIEL,
                'item\t%d\t%d' % (low, IN),
                'reward\t%d\t1' % high,
                'percent\t%d' % PCT,
                'gold\t%d' % GOLD,
                'end',
                '']
    return '\n'.join(out)


def check(text):
    """The cube.txt grammar Cube_load reads (cube.cpp): section ... end blocks of npc / item / reward / percent /
    gold (/ gaya / category ...) lines with tab-separated numbers; the Dockerfile's step tests the same counts."""
    errors = []
    blocks = re.findall(r'^section\r?\n(.*?)^end\r?$', text, re.S | re.M)
    if len(blocks) != len(FRUITS) - 1:
        errors.append('sections: %d, want %d' % (len(blocks), len(FRUITS) - 1))
    if text.count('section') != len(blocks):
        errors.append('a section without its end')
    for n, body in enumerate(blocks):
        rows = [r.split('\t') for r in body.replace('\r', '').strip().split('\n')]
        keys = [r[0] for r in rows]
        for r in rows:
            if r[0] not in ('npc', 'item', 'reward', 'percent', 'gold') or not all(x.isdigit() for x in r[1:]):
                errors.append('block %d: bad line %r' % (n, '\t'.join(r)))
        if keys.count('npc') != 1 or keys.count('reward') != 1 or keys.count('item') != 1:
            errors.append('block %d: npc/item/reward lines %r' % (n, keys))
        d = {r[0]: r[1:] for r in rows}
        low, high = FRUITS[n][0], FRUITS[n + 1][0]
        if d.get('npc') != [str(URIEL)] or d.get('item') != [str(low), str(IN)] or \
                d.get('reward') != [str(high), '1'] or d.get('percent') != [str(PCT)] or d.get('gold') != [str(GOLD)]:
            errors.append('block %d: %r' % (n, d))
    # the bots' copy of the numbers
    with open(BOT_H, encoding='latin-1') as f:
        h = f.read()
    for name, want in (('PLAYERBOT_FRUIT_CRAFT_IN', IN), ('PLAYERBOT_FRUIT_CRAFT_PERCENT', PCT),
                       ('PLAYERBOT_FRUIT_CRAFT_GOLD', GOLD)):
        m = re.search(r'\b%s\s*=\s*(\d+)\s*;' % name, h)
        if not m or int(m.group(1)) != want:
            errors.append('%s in playerbot_rank_points.h: %s, want %d' % (name, m.group(1) if m else None, want))
    return errors


def main():
    if '--check' not in sys.argv[1:]:
        with open(CUBE_OUT, 'w', newline='') as f:
            f.write(render() + '\n')
        print('wrote %s' % os.path.relpath(CUBE_OUT, REPO))
    with open(CUBE_OUT, newline='') as f:
        text = f.read()
    errors = check(text)
    if text != render() + '\n':
        errors.append('cube.owoce.txt is not what the generator writes - run it again')
    for e in errors:
        print('ERROR: ' + e)
    if errors:
        sys.exit(1)
    print('cube.owoce.txt: %d recipes OK (Uriel %d, %dx -> 1, %d%%, %d Yang)' % (len(FRUITS) - 1, URIEL, IN, PCT, GOLD))


if __name__ == '__main__':
    main()
