#!/usr/bin/env python3
"""gen_bonusy67c_sql.py - writes linux-port/docker/mariadb/playerbot/bonusy67c_wiki.sql (MT2009_PLUS_BONUS67_SKILL_V1):
the 6th/7th bonus pool's round 3 (the owner, 4 November 2026: every missing 6/7 bonus of the pl-wiki "6. i 7. bonus"
and the en-wiki "Bonuses" but the Lycan's - tools/bonusy67/bonusy67c_data.py), once per world (apply.sh, marker
rare_6_7_wiki_v4), after round 2 (rare_6_7_wiki_v3) and after item_attr_rare's apply ENUM has the names 256-318.
With --enum it prints the ENUM names apply.sh appends (in the points' order).

Like round 2 it never empties the pool: each of its rows is (re)written whole, every other row keeps the operator's
edits. A skill this world does not have (Wola Zycia 6, Krag Mieczy 21, Wolno Dzialajaca Trucizna 36) gets its row with
every column 0 - it rolls nowhere (the panel shows it; a column > 0 there turns it on once the skill exists).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bonusy67c_data as D  # noqa: E402

OUT = os.path.join(HERE, '..', '..', 'linux-port', 'docker', 'mariadb', 'playerbot', 'bonusy67c_wiki.sql')
KINDS = ('weapon', 'body', 'wrist', 'foots', 'neck', 'head', 'shield', 'ear', 'costume_body', 'costume_hair',
         'costume_weapon', 'pendant', 'glove')

HEADER = """-- MT2009_PLUS_BONUS67_SKILL_V1 (generated by tools/bonusy67/gen_bonusy67c_sql.py from bonusy67c_data.py - change that):
-- the 6th/7th bonus pool's round 3 (the owner, 4 November 2026: every missing 6/7 bonus of the pl-wiki "6. i 7. bonus"
-- and the en-wiki "Bonuses" but the Lycan's; server-patches/bonusy67c). apply.sh runs it ONCE per world (marker
-- rare_6_7_wiki_v4), after round 2 (bonusy67b_wiki.sql) and after the apply ENUMs have the names 256-318. It never
-- empties the pool: its rows are (re)written whole, the other rows keep the operator's edits. Items keep every bonus
-- they have (player.item is never touched). The rows of skills this world lacks (6, 21, 36) roll nowhere (all 0).
START TRANSACTION;
"""


def rows():
    out = []
    for p in D.POINTS:
        kinds = D.pool_kinds(p)
        out.append((p[1], p[9] if kinds else 0, p[7], kinds))
    out.extend(D.EXTRA_ROWS)
    return out


def main():
    if '--enum' in sys.argv:
        print(','.join("'%s'" % p[1] for p in D.POINTS))
        return
    text = HEADER
    for name, prob, values, kinds in rows():
        assert len(values) == 5 and all(k in KINDS and 0 <= lv <= 5 for k, lv in kinds.items()), name
        text += "DELETE FROM world.item_attr_rare WHERE apply = '%s';\n" % name
        text += ('INSERT INTO world.item_attr_rare (apply,prob,lv1,lv2,lv3,lv4,lv5,%s) VALUES (%s);\n'
                 % (','.join(KINDS), ','.join(["'%s'" % name, str(prob)] + [str(v) for v in values]
                                               + [str(kinds.get(k, 0)) for k in KINDS])))
    text += "INSERT IGNORE INTO world.mt2009_plus_once (name) VALUES ('rare_6_7_wiki_v4');\nCOMMIT;\n"
    with open(OUT, 'w', newline='\n') as f:
        f.write(text)
    print('%s: %d rows' % (os.path.normpath(OUT), len(rows())))


if __name__ == '__main__':
    main()
