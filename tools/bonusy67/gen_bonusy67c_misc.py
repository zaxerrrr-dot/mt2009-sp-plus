#!/usr/bin/env python3
"""gen_bonusy67c_misc.py - MT2009_PLUS_BONUS67_SKILL_V1: writes from bonusy67c_data.py (one table for everything)
  - linux-port/overlays/playerbot/src/game/src/playerbot_bonus67c_table.h  (the overlay's point -> kind / skill table)
  - client-patches/client-2.0.30/root/localeinfo_point.py                  (the item tooltip's lines, cp1250 escapes)
  - linux-port/docker/seban-panel/dbeditor/items.py                         (the panel's point names)
The two existing files get a block between "MT2009_PLUS_BONUS67_SKILL_V1 (begin)" / "(end)" comment lines - replaced on
every run (inserted before the anchor the first time), so a second run changes nothing."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bonusy67c_data as D  # noqa: E402

REPO = os.path.normpath(os.path.join(HERE, '..', '..'))
TABLE = os.path.join(REPO, 'linux-port', 'overlays', 'playerbot', 'src', 'game', 'src', 'playerbot_bonus67c_table.h')
LOCALE = os.path.join(REPO, 'client-patches', 'client-2.0.30', 'root', 'localeinfo_point.py')
PANEL = os.path.join(REPO, 'linux-port', 'docker', 'seban-panel', 'dbeditor', 'items.py')
M = 'MT2009_PLUS_BONUS67_SKILL_V1'


def ascii_pl(text):
    return text.translate(str.maketrans(u'ąćęłńóśźżĄĆĘŁŃÓŚŹŻ', u'acelnoszzACELNOSZZ'))


def py2_cp1250(text):
    """A Python 2 str literal body: cp1250 bytes, every byte above 127 as \\xNN (the file stays ASCII)."""
    out = []
    for b in text.encode('cp1250'):
        if b > 127:
            out.append('\\x%02x' % b)
        elif chr(b) in '"\\':
            out.append('\\' + chr(b))
        else:
            out.append(chr(b))
    return ''.join(out)


def write_if_changed(path, data, newline):
    data = data.replace('\r\n', '\n')
    if newline == '\r\n':
        data = data.replace('\n', '\r\n')
    raw = data.encode('utf-8')
    if os.path.exists(path) and open(path, 'rb').read() == raw:
        print('%s: unchanged' % os.path.relpath(path, REPO))
        return
    open(path, 'wb').write(raw)
    print('%s: written' % os.path.relpath(path, REPO))


def put_block(path, block, anchor, comment):
    raw = open(path, 'rb').read().decode('utf-8')
    newline = '\r\n' if '\r\n' in raw else '\n'
    text = raw.replace('\r\n', '\n')
    begin = '%s %s (begin)' % (comment, M)
    end = '%s %s (end)\n' % (comment, M)
    block = begin + '\n' + block + end
    if begin in text:
        a = text.index(begin)
        b = text.index(end, a) + len(end)
        text = text[:a] + block + text[b:]
    else:
        assert text.count(anchor) == 1, (path, anchor)
        text = text.replace(anchor, block + anchor)
    write_if_changed(path, text, newline)


def table():
    s = ('// ' + M + ' - generated by tools/bonusy67/gen_bonusy67c_misc.py from bonusy67c_data.py (change that).\n'
         '// The 6th/7th bonus points of the wiki round 3 (256-%d, server-patches/bonusy67c): point, kind, our skill vnum.\n'
         '// Included once, by playerbot_bonus67.cpp (inside its anonymous namespace, after TB67cLine / the B67C_* kinds).\n'
         % (D.WIDE_END - 1))
    s += 'const TB67cLine s_aB67cLine[] = {\n'
    for p in D.POINTS:
        s += '\t{ %s, B67C_%s, %d },\t// %d %s\n' % (p[1], p[2], p[3], p[0], ascii_pl(p[4]).replace('%%', '%').replace('%d', 'x'))
    s += '};\n'
    s += 'static_assert(POINT_WIDE_END == %d && POINT_%s == %d, "the round 3 points as bonusy67c_data.py has them");\n' % (
        D.WIDE_END, D.POINTS[0][1][6:], D.POINTS[0][0])
    write_if_changed(TABLE, s, '\n')


def locale():
    s = ('# The 6th/7th bonuses of the wiki round 3 (server-patches/bonusy67c, tools/bonusy67/bonusy67c_data.py - generated by\n'
         '# gen_bonusy67c_misc.py): the first two-byte points (256-%d) - the wiki\'s words; an item line of them needs the exe\n'
         '# with two-byte bonus types (app.MT2009_WIDE_ATTR_EXE). "Odpornosc na Upadek" (the body armour, POINT_IMMUNE_FALL 90)\n'
         '# is a chance now, no more a flag.\n' % (D.WIDE_END - 1))
    s += 'for _b67cPoint, _b67cName in (\n'
    for p in D.POINTS:
        s += '\t(%d, "%s"),\t# %s\n' % (p[0], py2_cp1250(p[4]), p[1])
    s += '\t):\n\tAFFECT_DICT.setdefault(_b67cPoint, _b67cName)\n'
    s += 'AFFECT_DICT[getattr(player, "POINT_IMMUNE_FALL", 90)] = "%s"\n' % py2_cp1250(D.FALL_TEXT)
    put_block(LOCALE, s, 'def Is1000PCT(affectType):\n', '#')


def panel():
    s = '    # the 6th/7th bonuses of the wiki round 3 (server-patches/bonusy67c, tools/bonusy67/gen_bonusy67c_misc.py)\n'
    for p in D.POINTS:
        s += '    %d: ("%s", "%s"),\n' % (p[0], p[5], p[6])
    put_block(PANEL, s, '}\nTECHNICAL_POINTS = {', '    #')


if __name__ == '__main__':
    table()
    locale()
    panel()
