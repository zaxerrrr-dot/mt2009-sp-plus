#!/usr/bin/env python3
"""gen_bonusy67b_sql.py - writes linux-port/docker/mariadb/playerbot/bonusy67b_wiki.sql (MT2009_PLUS_BONUS67_WIKI_V1):
the 6th/7th bonus pool's round 2 (the owner, 3 November 2026: "all the 6/7 bonuses of the wiki" - the pl-wiki
"6. i 7. bonus" and the en-wiki "Bonuses"), once per world (apply.sh, marker rare_6_7_wiki_v3), after
bonusy67_wiki.sql (round 1, rare_6_7_wiki_v2) and after item_attr_rare's apply ENUM has the names 253-255.

Unlike round 1 it never empties the pool: it adds its rows (a row of the same apply first removed - none of the three
new points had one) and changes only the columns named below, so the operator's other edits stay.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'linux-port', 'docker', 'mariadb', 'playerbot', 'bonusy67b_wiki.sql')

KINDS = ('weapon', 'body', 'wrist', 'foots', 'neck', 'head', 'shield', 'ear', 'costume_body', 'costume_hair',
         'costume_weapon', 'pendant', 'glove')
GEAR9 = ('weapon', 'body', 'wrist', 'foots', 'neck', 'head', 'shield', 'ear', 'pendant')

# (apply, prob, lv1..lv5, {kind: the highest level there}) - a row this step (re)writes whole
ROWS = [
    # "Jesli masz powyzej 90% PZ, doznajesz obrazenia nizsze o x%" - the body armour only, 1-5% (both wikis)
    ('POINT_RESIST_COMBAT', 18, (1, 2, 3, 4, 5), {'body': 5}),
    # "Atak krwawienia" / "Odpornosc na Atak Krwawienia" - every kind but the gloves, 1-5% (both wikis)
    ('POINT_BLEEDING_PCT', 18, (1, 2, 3, 4, 5), dict((k, 5) for k in GEAR9)),
    ('POINT_BLEEDING_REDUCE', 18, (1, 2, 3, 4, 5), dict((k, 5) for k in GEAR9)),
    # "Absorbuje obrazenia do x% jako PE" = the pl-wiki's "% obrazen bedzie dodanych do PE" (its link) = our
    # POINT_STEAL_SP (the 1-5 bonus of the helmet, armour and necklace). The pl-wiki: weapon and armour 5%, shoes 3%;
    # the en-wiki ("Absorbs (1, 2, 3%) damage as SP"): also the helmet, shield, bracelet, earrings and necklace (3%).
    ('POINT_STEAL_SP', 18, (1, 2, 3, 4, 5),
     {'weapon': 5, 'body': 5, 'foots': 3, 'head': 3, 'shield': 3, 'wrist': 3, 'ear': 3, 'neck': 3}),
    # "Absorbs (1, 2, 3%) damage as HP" - the en-wiki's shoes (our POINT_STEAL_HP, "x% obrazen dodanych do PZ")
    ('POINT_STEAL_HP', 18, (1, 2, 3, 4, 5), {'foots': 3}),
]

# column changes of rows round 1 wrote: (apply, {column: value})
UPDATES = [
    # round 1 took the wiki's "Absorbuje obrazenia do x% jako PE" for "Szansa na transfer x% otrzymanych obrazen do
    # PE" (POINT_DAMAGE_SP_RECOVER, a received blow) - the wiki's link says it is the damage DEALT (POINT_STEAL_SP,
    # above). The row stays (the panel shows it, items keep their lines) but rolls nowhere now.
    ('POINT_DAMAGE_SP_RECOVER', dict((k, 0) for k in KINDS)),
    # the en-wiki's talisman: "1st/2nd/3rd/4th/5th bonus + (1~25%)"
    ('POINT_FIRST_ATTRIBUTE_BONUS', {'pendant': 5}),
    ('POINT_SECOND_ATTRIBUTE_BONUS', {'pendant': 5}),
    ('POINT_THIRD_ATTRIBUTE_BONUS', {'pendant': 5}),
    ('POINT_FOURTH_ATTRIBUTE_BONUS', {'pendant': 5}),
    ('POINT_FIFTH_ATTRIBUTE_BONUS', {'pendant': 5}),
]

HEADER = """-- MT2009_PLUS_BONUS67_WIKI_V1 (generated by tools/bonusy67/gen_bonusy67b_sql.py - change that): the 6th/7th bonus
-- pool's round 2 (the owner, 3 November 2026: all the 6/7 bonuses of the pl-wiki "6. i 7. bonus" and the en-wiki
-- "Bonuses"; server-patches/bonusy67b). apply.sh runs it ONCE per world (marker rare_6_7_wiki_v3), after round 1
-- (bonusy67_wiki.sql) and after the apply ENUMs have POINT_RESIST_COMBAT / POINT_BLEEDING_PCT / POINT_BLEEDING_REDUCE
-- (253-255). It never empties the pool: its rows are (re)written whole, the other rows keep the operator's edits but
-- for the columns named below. Items keep every bonus they have (player.item is never touched).
START TRANSACTION;
"""


def main():
    text = HEADER
    for name, prob, values, kinds in ROWS:
        assert len(values) == 5 and all(k in KINDS and 0 <= lv <= 5 for k, lv in kinds.items())
        text += "DELETE FROM world.item_attr_rare WHERE apply = '%s';\n" % name
        text += ('INSERT INTO world.item_attr_rare (apply,prob,lv1,lv2,lv3,lv4,lv5,%s) VALUES (%s);\n'
                 % (','.join(KINDS), ','.join(["'%s'" % name, str(prob)] + [str(v) for v in values]
                                               + [str(kinds.get(k, 0)) for k in KINDS])))
    for name, cols in UPDATES:
        assert all(k in KINDS for k in cols)
        text += "UPDATE world.item_attr_rare SET %s WHERE apply = '%s';\n" % (
            ', '.join('%s = %d' % (k, v) for k, v in sorted(cols.items(), key=lambda kv: KINDS.index(kv[0]))), name)
    text += "INSERT IGNORE INTO world.mt2009_plus_once (name) VALUES ('rare_6_7_wiki_v3');\nCOMMIT;\n"
    with open(OUT, 'w', newline='\n') as f:
        f.write(text)
    print('%s: %d rows, %d updates' % (os.path.normpath(OUT), len(ROWS), len(UPDATES)))


if __name__ == '__main__':
    main()
