#!/usr/bin/env python3
"""gen_bonusy67_sql.py - writes linux-port/docker/mariadb/playerbot/bonusy67_wiki.sql (MT2009_PLUS_BONUS67_V1) from
bonusy67_data.py: the 6th/7th bonus pool of both bonus modes, once per world (apply.sh, marker rare_6_7_wiki_v2)."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bonusy67_data as D  # noqa: E402

OUT = os.path.join(HERE, '..', '..', 'linux-port', 'docker', 'mariadb', 'playerbot', 'bonusy67_wiki.sql')

HEADER = """-- MT2009_PLUS_BONUS67_V1 (generated by tools/bonusy67/gen_bonusy67_sql.py from bonusy67_data.py - change those):
-- the 6th/7th bonus pool (world.item_attr_rare: Seon-Hae, the Enchant 71051/71052) of BOTH bonus modes - the owner,
-- 20 October 2026: "Bonusy 6/7 takie same w jednym i drugim trybie" - the pl-wiki's "6. i 7. bonus": the 13 rows of
-- MT2009_PLUS_RARE_WIKI_V1 and the 54 bonuses the engine lacked until server-patches/bonusy67 (points 198-251).
-- apply.sh runs it ONCE per world (marker rare_6_7_wiki_v2 in world.mt2009_plus_once), after item_attr_rare's apply
-- ENUM has the new names: an operator's later edit stays, M2_BONUS_MODE no longer swaps the pool.
-- The owner's table of 1 October (the old mt2009 pool) stays as a backup in world.item_attr_rare_mt2009: a world that
-- was in global mode has it there already; one in mt2009 mode copies its pool there now. Items keep every bonus
-- they have (player.item is never touched).
-- Levels: Owsap's item_attr_rare (10 levels) at its 2nd/4th/6th/8th/10th (or 1-5 where it has five), ending at the
-- wiki's maximum; no official row (1.-5. dodany bonus, the gloves' lines): five equal steps to the wiki's maximum. A
-- kind column is the highest of the 5 levels that kind may reach (0 = never there). Weights equal (18); Burza
-- Szponow's cooldown line 0 (the Lycan's skill - no Lycan here).
CREATE TABLE IF NOT EXISTS world.item_attr_rare_mt2009 LIKE world.item_attr_rare;
SET @m2b67_saved := (SELECT COUNT(*) FROM world.item_attr_rare_mt2009);
START TRANSACTION;
INSERT INTO world.item_attr_rare_mt2009 SELECT * FROM world.item_attr_rare WHERE @m2b67_saved = 0;
DELETE FROM world.item_attr_rare;
"""


def row(r):
    name, prob, values, kinds = r
    cols = [str(kinds.get(k, 0)) for k in D.KINDS]
    return "('%s',%d,%s,%s)" % (name, prob, ','.join(str(v) for v in values), ','.join(cols))


def main():
    rows = D.OLD_ROWS + D.NEW_ROWS
    for r in rows:
        assert len(r[2]) == 5 and all(0 <= v <= 32767 for v in r[2])
        assert all(k in D.KINDS and 0 <= lv <= 5 for k, lv in r[3].items())
    text = HEADER
    text += ('INSERT INTO world.item_attr_rare (apply,prob,lv1,lv2,lv3,lv4,lv5,%s) VALUES\n' % ','.join(D.KINDS))
    text += ',\n'.join(row(r) for r in rows) + ';\n'
    text += "INSERT IGNORE INTO world.mt2009_plus_once (name) VALUES ('rare_6_7_wiki_v2');\nCOMMIT;\n"
    with open(OUT, 'w', newline='\n') as f:
        f.write(text)
    print('%s: %d rows' % (os.path.normpath(OUT), len(rows)))


if __name__ == '__main__':
    main()
