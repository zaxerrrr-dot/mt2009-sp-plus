#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_ylokacje.py [--from-xlsx FILE] [--radius M]

MT2009_PLUS_YOHARA_LOKACJE_V1: every published spawn point of the Yohara maps (the owner's spreadsheet of 20 October
2026, "Metin2_Yohara_moby_i_lokalizacje.xlsx", sheet Lokalizacje: 1101 points of 24 maps, read 16.10.2026; its
points are GF 26.1.11's npc_location_helper/map_mob_list.txt - 216 of its 218 lists are the same, plus Natanan
(mrok) 6705 on Dongan) gets a spawn of that monster: a point no spawn of the monster reaches (centre within
--radius m, 40 by default) gets one here. Nothing of the batches' own files is taken away - the sheet's notes:
"Brak listy lub stalego punktu w zrodle nie oznacza braku respawnu w grze"; it gives no counts and no times.

  monsters  an "m" line at the point, the map's usual number of monsters a spawn (the median of its regen lines:
            m -> count, g -> the group, r -> the mean group of its group_group), the monster's own respawn on that
            map (else the map's usual one), range 10;
  bosses    (the sheet's rank Boss) into boss.txt, the monster's own respawn there (else the map's boss one);
            a point the sheet gives several bosses (Przelecz Yilad: the four Wodzowie at the same two points) gets
            ONE random of them - an "r" line of our group_group (one boss a group) - and only when none of them
            stands there already;
  Metins    (vnums 8000-8999) into stone.txt, the Metin's own respawn there (else the map's stone one);
  skipped   the quest-only "(misja)" ones (Metin Swiadomosc 8062, Krol Bao 6692) and maps without a fixed point
            (the sheet's "Brak stalego punktu" - quest dungeons) or not ours (415, 420-425: no such map yet).

Every centre is on free ground of GF's attr.atr (the batches' terrain), a blocked one moved to the nearest free
metre (25 m at most, else left out and reported). Coordinates: the sheet's "X/Y lokalne" = raw / 100 = metres from
the map's base, the same as regen.txt's; checked against each map's MapSize.

Reads   tools/yohara_lokacje/lokalizacje.tsv (made from the xlsx by --from-xlsx, needs openpyxl)
        linux-port/docker/game/yohara_*/map/<folder>/{regen,boss,stone}.txt, yohara_*/group*.txt
Writes  (GENERATED - edit this file, run it again)
        linux-port/docker/game/yohara_lokacje/map/<folder>/{regen,boss,stone}.lokacje.txt  (appended by the
            Dockerfile step "MT2009_PLUS_YOHARA_LOKACJE_V1" to the map's own files)
        linux-port/docker/game/yohara_lokacje/group.yohara_lokacje.txt        groups 9400-9439 (one boss each)
        linux-port/docker/game/yohara_lokacje/group_group.yohara_lokacje.txt  group_groups 4060-4069
        linux-port/docker/game/yohara_lokacje/spawned.txt, gen_report.txt

  /opt/metin2/cache/xlsxenv/bin/python tools/yohara_lokacje/gen_ylokacje.py --from-xlsx <xlsx>   (once)
  python3 tools/yohara_lokacje/gen_ylokacje.py
"""
import argparse
import collections
import glob
import math
import os
import re
import shutil
import statistics
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
GAME = os.path.join(REPO, 'linux-port', 'docker', 'game')
OUT = os.path.join(GAME, 'yohara_lokacje')
TSV = os.path.join(HERE, 'lokalizacje.tsv')
sys.path.insert(0, os.path.join(REPO, 'tools', 'yohara_maps'))

# our Yohara maps: index -> folder (map/index of game3 / game2)
FOLDERS = collections.OrderedDict([
    (373, 'metin2_map_eastplain_01'), (374, 'metin2_map_empirecastle'), (376, 'metin2_map_eastplain_02'),
    (377, 'metin2_map_eastplain_03'), (382, 'metin2_map_maze_dungeon1'), (383, 'metin2_map_maze_dungeon2'),
    (384, 'metin2_map_maze_dungeon3'), (385, 'metin2_map_snakevalley'), (388, 'metin2_map_icecrystalcave'),
    (389, 'metin2_map_whitdragonvalley'), (390, 'metin2_map_snake_temple_01'), (393, 'metin2_map_whitedragoncave_01'),
    (394, 'metin2_map_whitedragoncave_02'), (396, 'metin2_map_anglar_dungeon_01'),
    # quest dungeons (no fixed point in the sheet): nothing to add
    (386, 'metin2_map_smhdungeon_01'), (391, 'metin2_map_snake_temple_02'), (395, 'metin2_map_whitedragoncave_boss'),
])
GROUP_FIRST, GROUP_LAST = 9400, 9439
GGROUP_FIRST, GGROUP_LAST = 4060, 4069


def from_xlsx(path):
    import openpyxl
    wb = openpyxl.load_workbook(path, read_only=False)
    rank = {}
    for r in wb['Moby na mapach'].iter_rows(min_row=7, values_only=True):
        if r[1] and r[4]:
            rank[(int(r[1]), int(r[4]))] = r[6] or ''
    n = 0
    with open(TSV, 'w', encoding='utf-8') as f:
        f.write('# MT2009_PLUS_YOHARA_LOKACJE_V1: the sheet "Lokalizacje" of %s (metin2alerts.com/pl/wiki/maps, read '
                '16.10.2026; GENERATED by gen_ylokacje.py --from-xlsx).\n' % os.path.basename(path))
        f.write('# map\tvnum\trank\tname\tx\ty  (x/y local metres = raw / 100; empty = no fixed point)\n')
        for r in wb['Lokalizacje'].iter_rows(min_row=7, values_only=True):
            if not r[1]:
                continue
            m, v = int(r[1]), int(r[3])
            x = '' if r[5] is None else str(int(r[5]))
            y = '' if r[6] is None else str(int(r[6]))
            f.write('%d\t%d\t%s\t%s\t%s\t%s\n' % (m, v, rank.get((m, v), ''), r[2], x, y))
            n += 1
    print('%s: %d rows' % (TSV, n))


def read_sheet():
    pts = collections.defaultdict(lambda: collections.defaultdict(list))
    info = {}
    for l in open(TSV, encoding='utf-8'):
        if l.startswith('#') or not l.strip():
            continue
        m, v, rank, name, x, y = l.rstrip('\n').split('\t')
        m, v = int(m), int(v)
        info[(m, v)] = (rank, name)
        pts[m][v]
        if x:
            pts[m][v].append((int(x), int(y)))
    return pts, info


def read_groups():
    """group vnum -> [member vnums], group_group vnum -> [group vnums] of every Yohara batch."""
    groups, ggroups = {}, {}
    for path in sorted(glob.glob(os.path.join(GAME, 'yohara_*', 'group*.txt'))):
        if os.path.dirname(path) == OUT:
            continue
        gg = os.path.basename(path).startswith('group_group')
        text = open(path, encoding='latin-1').read().replace('\r', '')
        for body in re.findall(r'Group\s+\S+\s*\{(.*?)\n\}', text, re.S):
            v = re.search(r'Vnum\s+(\d+)', body)
            if not v:
                continue
            mem = []
            for line in body.split('\n'):
                t = line.split()
                if not t or t[0] == 'Vnum':
                    continue
                if gg and t[0].isdigit() and len(t) >= 2:
                    mem.append(int(t[1]))
                elif not gg and (t[0] == 'Leader' or t[0].isdigit()) and t[-1].isdigit():
                    mem.append(int(t[-1]))
            (ggroups if gg else groups)[int(v.group(1))] = mem
    return groups, ggroups


def map_files(folder):
    """name -> path of the batch's own spawn files of a map (exactly one batch has the folder)."""
    dirs = [d for d in glob.glob(os.path.join(GAME, 'yohara_*', 'map', folder)) if not d.startswith(OUT)]
    if len(dirs) != 1:
        raise SystemExit('%s: %d batch folders %s' % (folder, len(dirs), dirs))
    return dirs[0], {n: os.path.join(dirs[0], n) for n in ('regen.txt', 'boss.txt', 'stone.txt')
                     if os.path.exists(os.path.join(dirs[0], n))}


def spawn_lines(path):
    out = []
    for l in open(path, encoding='latin-1'):
        t = l.split()
        if len(t) >= 11 and t[0] in ('m', 'g', 'r', 's') and not l.lstrip().startswith('//'):
            out.append(t)
    return out


def line(kind, x, y, r, t, vnum, count=1):
    return '%s\t%d\t%d\t%d\t%d\t0\t0\t%s\t100\t%d\t%d' % (kind, x, y, r, r, t, count, vnum)


def mode(values, default):
    c = collections.Counter(values)
    return c.most_common(1)[0][0] if c else default


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--from-xlsx', help="write tools/yohara_lokacje/lokalizacje.tsv from the owner's xlsx and stop")
    ap.add_argument('--radius', type=int, default=40, help='a spawn centre this near covers a point (m)')
    a = ap.parse_args()
    if a.from_xlsx:
        from_xlsx(a.from_xlsx)
        return
    import gen_ymaps2 as m2  # noqa: E402  (GF's attr.atr grid)
    R = a.radius
    sheet, info = read_sheet()
    groups, ggroups = read_groups()
    rep = []

    def say(s):
        rep.append(s)
        print(s)

    def members(kind, v):
        if kind == 'm':
            return [v]
        if kind in ('g',):
            if v not in groups:
                raise SystemExit('group %d unknown' % v)
            return groups[v]
        if v not in ggroups:
            raise SystemExit('group_group %d unknown' % v)
        out = []
        for gv in ggroups[v]:
            if gv not in groups:
                raise SystemExit('group %d (of group_group %d) unknown' % (gv, v))
            out += groups[gv]
        return out

    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)
    new_groups, new_ggroups = [], []
    spawned = []
    totals = collections.Counter()
    say('MT2009_PLUS_YOHARA_LOKACJE_V1 - points of the sheet a spawn of the monster does not reach within %d m' % R)
    for m in sorted(sheet):
        if m not in FOLDERS:
            say('%d: not our map (%d monsters, %d points) - nothing' % (
                m, len(sheet[m]), sum(len(p) for p in sheet[m].values())))
            continue
        folder = FOLDERS[m]
        if not any(sheet[m].values()):
            say('%d %s: no fixed point in the sheet (quest dungeon) - nothing' % (m, folder))
            continue
        d, files = map_files(folder)
        st = open(os.path.join(d, 'Setting.txt'), encoding='latin-1').read()
        w, h = (int(v) for v in re.search(r'MapSize\s+(\d+)\s+(\d+)', st).groups())
        grid = m2.Grid(folder, (w, h))
        ents = []           # (file, kind, x, y, respawn, members)
        for n, p in files.items():
            for t in spawn_lines(p):
                ents.append((n, t[0], int(t[1]), int(t[2]), t[7], int(t[9]), members(t[0], int(t[10])), int(t[10])))
        sizes = []
        for e in ents:
            if e[0] != 'regen.txt':
                continue
            if e[1] == 'm':
                sizes.append(e[5])
            elif e[1] == 'g':
                sizes.append(len(e[6]))
            else:
                sizes.append(round(len(e[6]) / float(len(ggroups[e[7]]))))
        count = max(1, min(5, int(statistics.median(sizes)))) if sizes else 1
        t_regen = mode([e[4] for e in ents if e[0] == 'regen.txt'], '60s')
        t_boss = mode([e[4] for e in ents if e[0] == 'boss.txt'], '3600s')
        if int(t_boss.rstrip('s')) < 600:     # Opuszczona Twierdza: Owsap's Krol Bao every 10 s - not a boss default
            t_boss = '3600s'
        t_stone = mode([e[4] for e in ents if e[0] == 'stone.txt'], '1800s')
        say('%d %s (%dx%d = %dx%d m): %d spawn lines; a monster spawn here: %d, %s; boss %s; Metin %s' % (
            m, folder, w, h, w * 256, h * 256, len(ents), count, t_regen, t_boss, t_stone))
        out = collections.defaultdict(list)
        covered_by = lambda v, x, y: [e for e in ents if v in e[6] and math.hypot(e[2] - x, e[3] - y) <= R]  # noqa
        def own_time(v, f, dflt):
            """the monster's respawn in that file of the map, else in any of its files, else the default"""
            return mode([e[4] for e in ents if v in e[6] and e[0] == f],
                        mode([e[4] for e in ents if v in e[6]], dflt))
        boss_at = collections.defaultdict(list)
        for v, pts in sorted(sheet[m].items()):
            rank, name = info[(m, v)]
            for (x, y) in pts:
                if not (0 <= x < w * 256 and 0 <= y < h * 256):
                    raise SystemExit('%d %d %s: %d,%d outside the map' % (m, v, name, x, y))
            if '(misja)' in name:
                say('  %d %s: a quest monster - skipped (%d points)' % (v, name, len(pts)))
                continue
            if rank == 'Boss':
                for p in pts:
                    boss_at[p].append(v)
                continue
            stone = 8000 <= v < 9000
            for (x, y) in pts:
                if covered_by(v, x, y):
                    continue
                p = grid.nearest_free(x, y, 25)
                if p is None:
                    say('  %d %s at %d,%d: no free ground within 25 m - left out' % (v, name, x, y))
                    continue
                if stone:
                    out['stone.txt'].append(line('m', p[0], p[1], 10, own_time(v, 'stone.txt', t_stone), v))
                else:
                    out['regen.txt'].append(line('m', p[0], p[1], 10, own_time(v, 'regen.txt', t_regen), v, count))
                say('  + %-5s %d %s at %d,%d%s' % ('stone' if stone else 'mob', v, name, p[0], p[1],
                                                  '' if p == (x, y) else ' (GF %d,%d blocked)' % (x, y)))
                spawned.append((m, v))
        # the sheet's boss points within R of each other are one place (Dongan: Natanan / Argos of both elements
        # at 930,500-521) - its bosses together, the first point the place
        places = []
        for (x, y), vs in sorted(boss_at.items()):
            for pl in places:
                if any(math.hypot(x - a, y - b) <= R for a, b in pl[0]):
                    pl[0].append((x, y))
                    pl[1].update(vs)
                    break
            else:
                places.append([[(x, y)], set(vs)])
        for pl in places:
            (x, y), vs = pl[0][0], sorted(pl[1])
            names = '/'.join('%d %s' % (v, info[(m, v)][1]) for v in vs)
            if any(covered_by(v, a, b) for v in vs for a, b in pl[0]):
                continue
            p = grid.nearest_free(x, y, 25)
            if p is None:
                say('  boss %s at %d,%d: no free ground within 25 m - left out' % (names, x, y))
                continue
            t = max((own_time(v, 'boss.txt', t_boss) for v in vs), key=lambda s: int(s.rstrip('sm')))
            if len(vs) == 1:
                out['boss.txt'].append(line('m', p[0], p[1], 10, t, vs[0]))
            else:
                key = tuple(vs)
                gg = [g for g in new_ggroups if g[1] == key]
                if not gg:
                    gvs = []
                    for v in vs:
                        if not any(g[1] == v for g in new_groups):
                            new_groups.append((GROUP_FIRST + len(new_groups), v, info[(m, v)][1]))
                        gvs.append([g[0] for g in new_groups if g[1] == v][0])
                    new_ggroups.append((GGROUP_FIRST + len(new_ggroups), key, gvs))
                    gg = [new_ggroups[-1]]
                out['boss.txt'].append(line('r', p[0], p[1], 10, t, gg[0][0]))
            say('  + boss  %s at %d,%d, %s%s' % (names + (' (one at random)' if len(vs) > 1 else ''), p[0], p[1], t,
                                               '' if p == (x, y) else ' (GF %d,%d blocked)' % (x, y)))
            for v in vs:
                spawned.append((m, v))
        if out:
            od = os.path.join(OUT, 'map', folder)
            os.makedirs(od)
            for n, ls in out.items():
                with open(os.path.join(od, n.replace('.txt', '.lokacje.txt')), 'w', encoding='latin-1') as f:
                    f.write('\n'.join(ls) + '\n')
                totals[n] += len(ls)
            say('  = %s' % ', '.join('%s +%d' % (n, len(ls)) for n, ls in sorted(out.items())))
    if new_groups[-1:] and new_groups[-1][0] > GROUP_LAST or new_ggroups[-1:] and new_ggroups[-1][0] > GGROUP_LAST:
        raise SystemExit('group numbers used up')

    def ascii_pl(s):
        return s.translate(str.maketrans('ąćęłńóśźżĄĆĘŁŃÓŚŹŻ', 'acelnoszzACELNOSZZ')).replace(' ', '_')

    with open(os.path.join(OUT, 'group.yohara_lokacje.txt'), 'w', encoding='latin-1') as f:
        f.write('// MT2009_PLUS_YOHARA_LOKACJE_V1: one boss a group (GENERATED by tools/yohara_lokacje/gen_ylokacje.py)\n')
        for gv, v, name in new_groups:
            f.write('Group\tMT2009_ylok_%s_%d\n{\n\tLeader\t%s\t%d\n\tVnum\t%d\n}\n' % (
                ascii_pl(name), v, ascii_pl(name), v, gv))
    with open(os.path.join(OUT, 'group_group.yohara_lokacje.txt'), 'w', encoding='latin-1') as f:
        f.write('// MT2009_PLUS_YOHARA_LOKACJE_V1: one of the bosses the sheet gives a point (GENERATED)\n')
        for ggv, key, gvs in new_ggroups:
            f.write('Group\tMT2009_ylok_%s\n{\n\tVnum\t%d\n' % ('_'.join(str(v) for v in key), ggv))
            for k, gv in enumerate(gvs, 1):
                f.write('\t%d\t%d\t1\n' % (k, gv))
            f.write('}\n')
    with open(os.path.join(OUT, 'spawned.txt'), 'w', encoding='utf-8') as f:
        f.write('# MT2009_PLUS_YOHARA_LOKACJE_V1: the vnums this adds to each map (GENERATED): <map index> <vnum>\n')
        for m, v in sorted(set(spawned)):
            f.write('%d %d\n' % (m, v))
    say('total: %s; groups %d, group_groups %d' % (', '.join('%s +%d' % kv for kv in sorted(totals.items())),
                                                   len(new_groups), len(new_ggroups)))
    with open(os.path.join(OUT, 'gen_report.txt'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(rep) + '\n')


if __name__ == '__main__':
    main()
