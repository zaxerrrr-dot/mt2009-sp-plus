#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_ybiolog_items.py [--owsap DIR] [--gf DIR]

MT2009_PLUS_BIOLOGIST_YOHARA_V1: the three items of Chaegirab's (Dongan, 20810) research on the new continent (the
owner, 29 October 2026: "dodaj kolejne misje Biologa wedlug wiki" - pl-wiki "Misje Biologa": "Oczyszczone Rdzenie",
"Krysztaly Metin", "Mroczne Paprocie"), which our world did not have. The official vnums and numbers of Owsap v6.2.6
(Server/Server/db/item_proto.txt: ITEM_QUEST, stackable, 1000 / 50 Yang), the Polish names and descriptions of its
Polish client (= the official translation), the icons of the GF 26.1.11 client (shared/common/item_list.txt):

  31230 Oczyszczony Rdzen   icon 31221.tga   quest collect_quest_cz1  (every monster of Yohara)
  31231 Krysztal Metin      icon 31229.tga   quest collect_quest_cz10 (Metin Szacunku / Uwaznosci / Jin / Swiadomosc)
  31232 Mroczna Paproc      icon 31222.tga   quest collect_quest_cz20 (every monster of Jaskinie Gnolli)

They are ITEM_MATERIAL here, as every Biologist specimen of this world (30251 Klejnot Zawisci, 30168 Notatka
Przywodcy: type 5) and Skazony Rdzen 31226; tradeable, stackable to 200 (the wiki: "Handlowanie z Graczem: Tak").
The drops are the quests' own kill hooks (only while the mission waits for them, as the Biologist's earlier rows);
Plat. Skrzynia Skarbow (83055) has them again by the owner's sheet (tools/yohara_chestdrops: no longer SKIP).

Writes (all GENERATED - edit this file, run it again):
  linux-port/docker/mariadb/playerbot/yohara_biolog.sql      world.item_proto (INSERT IGNORE)
  tools/ybiolog/ybiolog_items.json                           the client's records, item_list and itemdesc rows
                                                             (client-patches/client-2.0.30/tools/ybiolog)
  client-patches/client-2.0.30/root/icon/item/<icon>.tga     the GF icons

Example: python3 tools/ybiolog/gen_ybiolog_items.py
"""
import argparse
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, 'tools', 'yohara_items'))
import gen_yitems as Y  # noqa: E402  (the item row writer)

M = 'MT2009_PLUS_BIOLOGIST_YOHARA_V1'
SQL_OUT = os.path.join(REPO, 'linux-port', 'docker', 'mariadb', 'playerbot', 'yohara_biolog.sql')
JSON_OUT = os.path.join(HERE, 'ybiolog_items.json')
ICON_OUT = os.path.join(REPO, 'client-patches', 'client-2.0.30', 'root', 'icon', 'item')

VNUMS = (31230, 31231, 31232)
MATERIAL = 5
STACKABLE = 4


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--owsap', default='/opt/metin2/cache/owsap')
    ap.add_argument('--gf', default='/opt/metin2/cache/gf/Gameforge_26.1.11/_client')
    a = ap.parse_args()
    rows = Y.read_tsv(os.path.join(a.owsap, 'Server/Server/db/item_proto.txt'))
    head = rows[0]
    proto = dict((int(r[0]), dict(zip(head, r))) for r in rows[1:] if r and r[0].isdigit())
    desc = {}
    for r in Y.read_tsv(os.path.join(a.owsap, 'Client/Client/pack/locale/locale/pl/itemdesc.txt')):
        if len(r) >= 2 and r[0].strip().isdigit():
            desc[int(r[0])] = (r[1].strip(), r[2].strip() if len(r) > 2 else '')
    gf_list = {}
    for r in Y.read_tsv(os.path.join(a.gf, 'shared/common/item_list.txt')):
        if len(r) >= 3 and r[0].strip().isdigit():
            gf_list[int(r[0])] = r[2].strip()
    items = []
    for v in VNUMS:
        o = proto[v]
        assert o['Type'] == 'ITEM_QUEST' and o['Flags'] == 'ITEM_STACKABLE', (v, o['Type'], o['Flags'])
        name, text = desc[v]
        assert name and len(name.encode('cp1250')) <= 24, (v, name)
        icon = gf_list[v]
        items.append(dict(
            vnum=v, status=Y.ST, name=Y.ascii_name(name), locale_name=name, type=MATERIAL, subtype=0, stack=200,
            weight=0, size=int(o['Size']), antiflag=0, flag=STACKABLE, wearflag=0, gold=int(o['ShopBuyPrice']),
            shop_buy_price=int(o['ShopSellPrice']), refined_vnum=0, refine_set=0, magic_pct=0, specular=0,
            socket_pct=0, addon_type=0, limittype0=0, limitvalue0=0, limittype1=0, limitvalue1=0,
            applytype0=0, applyvalue0=0, applytype1=0, applyvalue1=0, applytype2=0, applyvalue2=0,
            value0=0, value1=0, value2=0, value3=0, value4=0, value5=0,
            icon='icon/item/' + os.path.basename(icon), icon_src=icon, desc=text, list_type='ETC'))
    write_sql(items)
    write_json(items)
    copy_icons(items, a.gf)
    print('items %d: %s' % (len(items), ', '.join('%d %s' % (i['vnum'], i['name']) for i in items)))


def write_sql(items):
    L = ['-- %s: the specimens of Chaegirab\'s (Dongan, 20810) research on the new continent - pl-wiki' % M,
         '-- "Misje Biologa" (Oczyszczone Rdzenie, Krysztaly Metin, Mroczne Paprocie; the owner, 29 October 2026).',
         '-- GENERATED by tools/ybiolog/gen_ybiolog_items.py - do not edit, rerun it. Every start (apply.sh),',
         '-- idempotent: INSERT IGNORE - a row the operator changed is kept. Owsap v6.2.6\'s vnums and prices, its',
         '-- Polish client\'s names; a material as every Biologist specimen here, tradeable and stackable. The quests',
         '-- collect_quest_cz1 / cz10 / cz20 (game/quest) drop and take them; Plat. Skrzynia Skarbow 83055 holds them',
         '-- (game/yohara_maps4/special_item_group.yohara_items4.txt): a world without these rows stops the cores at boot.',
         'SET NAMES utf8mb4;',
         'INSERT IGNORE INTO world.item_proto (%s) VALUES' % ','.join('`%s`' % c for c in Y.COLS),
         ',\n'.join(Y.sqlrow(i) for i in items) + ';']
    with open(SQL_OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(L) + '\n')


def write_json(items):
    keys = ('vnum', 'name', 'locale_name', 'type', 'subtype', 'stack', 'weight', 'size', 'antiflag', 'flag',
            'wearflag', 'gold', 'shop_buy_price', 'refined_vnum', 'refine_set', 'magic_pct', 'specular', 'socket_pct',
            'limittype0', 'limitvalue0', 'limittype1', 'limitvalue1', 'applytype0', 'applyvalue0', 'applytype1',
            'applyvalue1', 'applytype2', 'applyvalue2', 'value0', 'value1', 'value2', 'value3', 'value4', 'value5')
    out = {'items': [dict((k, i[k]) for k in keys) for i in items],
           'item_list': dict((str(i['vnum']), '%d\t%s\t%s' % (i['vnum'], i['list_type'], i['icon'])) for i in items),
           'itemdesc': dict((str(i['vnum']), '%d\t%s\t%s' % (i['vnum'], i['locale_name'], Y.client_desc(i)))
                            for i in items)}
    with open(JSON_OUT, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(out, f, ensure_ascii=False, indent=0)
        f.write('\n')


def copy_icons(items, gf):
    os.makedirs(ICON_OUT, exist_ok=True)
    for i in items:
        dst = os.path.join(ICON_OUT, os.path.basename(i['icon']))
        src = os.path.join(gf, i['icon_src'].replace('\\', '/'))
        assert os.path.isfile(src), src
        if not os.path.exists(dst):
            shutil.copyfile(src, dst)


if __name__ == '__main__':
    main()
