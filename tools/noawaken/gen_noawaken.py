#!/usr/bin/env python3
"""gen_noawaken.py

MT2009_PLUS_NO_AWAKENING_V1 (the owner, 15 October 2026, Yohara 3.0): the Ritual of Awakening and the awakened
weapons (Digi Rasta's MT2009_PLUS_AWAKENING_V1, release 2.19.0) are gone. The seven families it took over -
210, 220, 1160, 2190, 3170, 5150, 7170 (+0..+9) - get back the rows the world had before 3 October: the mod's
own dump, linux-port/docker/mariadb/playerbot/item_proto.mt2009plus.sql (25 September), which are the official
rows (Owsap v6.2.6's item_proto.txt has the same placeholders: no level, no attack - except Upiorna Kusza,
level 38, and Hibiskusowy Dzwon, level 52). Names are not touched (the awakening never changed them).

The players' awakened weapons become the official weapon of level 87 of the same kind at the same plus
(AWAKENED_TO_OFFICIAL: same subtype, same class flags, same three sockets; Wachlarz Lezac. Smoka is that
family's own pl-wiki name - 7370, not the placeholder 7170). They had no other source since 3 October
(2190/5150 dropped nowhere before), so every piece of those vnums is an awakened one.

Writes (GENERATED - edit this file, run it again):
  linux-port/docker/mariadb/playerbot/noawaken.sql    once per world (apply.sh, marker no_awakening_v1)
  tools/noawaken/noawaken_client.json                 the client records' fields (client-patches/client-2.0.30/
                                                      tools/noawaken/patch_noawaken_client.py reads it)

Example: python3 tools/noawaken/gen_noawaken.py
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DUMP = os.path.join(ROOT, 'linux-port/docker/mariadb/playerbot/item_proto.mt2009plus.sql')
OUT_SQL = os.path.join(ROOT, 'linux-port/docker/mariadb/playerbot/noawaken.sql')
OUT_JSON = os.path.join(ROOT, 'tools/noawaken/noawaken_client.json')

# The awakened family +0 -> the official level-87 family +0 of the same kind (subtype, antiflag).
AWAKENED_TO_OFFICIAL = (
    (210, 460),     # Smiercionosne Ostrze  -> Runiczny Miecz          (sword, all sword classes)
    (220, 470),     # Ksiezycowy Miecz      -> Klinga Smoczego Kla     (sword, Sura)
    (1160, 1340),   # Noz Strumienia        -> Kolec Pieciu Elementow  (daggers)
    (2190, 2370),   # Upiorna Kusza         -> Luk Feniksa             (bow)
    (3170, 3190),   # Zabojca Zolt. Smoka   -> Ostrze Slonca           (two-handed)
    (5150, 5340),   # Hibiskusowy Dzwon     -> Dzwon Smoczego Ducha    (bell)
    (7170, 7370),   # Wachlarz Lezac. Smoka -> Wachlarz Lezac. Smoka   (fan; the wiki's item)
)
# Recipes only the awakening used: 7100-7108 its steps, 7110 the ritual (the soul stones' 7204-7208 stay).
DEAD_RECIPES = (7100, 7101, 7102, 7103, 7104, 7105, 7106, 7107, 7108, 7110)
STONE_VNUM = 30670  # Kamien Przebudzenia: kept for the pieces players hold, no source any more

# Restored columns (all but vnum and the names).
COLS = ('type', 'subtype', 'stack', 'weight', 'size', 'antiflag', 'flag', 'wearflag', 'immuneflag', 'gold',
        'shop_buy_price', 'refined_vnum', 'refine_set', 'magic_pct', 'specular', 'socket_pct', 'addon_type',
        'limittype0', 'limitvalue0', 'limittype1', 'limitvalue1', 'applytype0', 'applyvalue0', 'applytype1',
        'applyvalue1', 'applytype2', 'applyvalue2', 'value0', 'value1', 'value2', 'value3', 'value4', 'value5',
        'socket0', 'socket1', 'socket2', 'socket3', 'socket4', 'socket5')


def split_row(text):
    """One '(...)' row of the dump into its fields (quoted strings kept as Python strings)."""
    out, cur, quoted, i = [], '', False, 0
    while i < len(text):
        c = text[i]
        if quoted:
            if c == '\\':
                cur += text[i + 1]
                i += 2
                continue
            if c == "'":
                if text[i + 1:i + 2] == "'":
                    cur += "'"
                    i += 2
                    continue
                quoted = False
            else:
                cur += c
        elif c == "'":
            quoted = True
        elif c == ',':
            out.append(cur)
            cur = ''
        else:
            cur += c
        i += 1
    out.append(cur)
    return out


def main():
    text = open(DUMP, encoding='utf-8').read()
    header = re.search(r'INSERT IGNORE INTO world\.item_proto \(([^)]*)\) VALUES', text)
    names = [c.strip('` ') for c in header.group(1).split(',')]
    want = set(b + n for b, _ in AWAKENED_TO_OFFICIAL for n in range(10))
    rows = {}
    for m in re.finditer(r'^\((\d+),(.*)\)[,;]\s*$', text, re.M):
        vnum = int(m.group(1))
        if vnum in want:
            fields = split_row(m.group(1) + ',' + m.group(2))
            rows[vnum] = dict(zip(names, fields))
    missing = sorted(want - set(rows))
    assert not missing, missing

    lines = [
        '-- GENERATED by tools/noawaken/gen_noawaken.py - edit that, run it again.',
        '-- MT2009_PLUS_NO_AWAKENING_V1 (the owner, 15 October 2026, Yohara 3.0): the awakened weapons are gone.',
        '-- Run ONCE per world by apply.sh (marker no_awakening_v1 in world.mt2009_plus_once): after it 2190-2199',
        '-- and 5150-5159 are the official Upiorna Kusza / Hibiskusowy Dzwon again, which a second run would move.',
        'SET NAMES utf8mb4;',
        '',
        '-- 1. The seven families +0..+9: the rows of item_proto.mt2009plus.sql (the world before 3 October).',
    ]
    for vnum in sorted(rows):
        r = rows[vnum]
        sets = ', '.join('`%s` = %s' % (c, "'%s'" % r[c] if c == 'immuneflag' else int(r[c])) for c in COLS)
        lines.append('UPDATE world.item_proto SET %s WHERE vnum = %d;' % (sets, vnum))
    lines += [
        '',
        '-- 2. The awakening\'s own recipes (refine_proto); nothing names them any more.',
        'DELETE FROM world.refine_proto WHERE id IN (%s);' % ', '.join(str(i) for i in DEAD_RECIPES),
        '',
        '-- 3. The awakened pieces (bags, equipment, storage, offline shops - every window of player.item - and',
        '--    the awards not yet taken) become the official level-87 weapon of the same kind at the same plus;',
        '--    bonuses, stones and sockets stay on the piece.',
    ]
    for awakened, official in AWAKENED_TO_OFFICIAL:
        for table in ('player.item', 'player.item_award'):
            lines.append('UPDATE %s SET vnum = vnum - %d + %d WHERE vnum BETWEEN %d AND %d;'
                         % (table, awakened, official, awakened, awakened + 9))
    lines.append('')
    open(OUT_SQL, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))

    client = {
        'marker': 'MT2009_PLUS_NO_AWAKENING_V1',
        'stone_vnum': STONE_VNUM,
        'records': {str(v): dict((c, rows[v][c] if c == 'immuneflag' else int(rows[v][c])) for c in COLS)
                    for v in sorted(rows)},
    }
    open(OUT_JSON, 'w', encoding='utf-8', newline='\n').write(json.dumps(client, indent=1, sort_keys=True) + '\n')
    print('noawaken: %d rows, %d recipes dropped, %d families moved -> %s, %s'
          % (len(rows), len(DEAD_RECIPES), len(AWAKENED_TO_OFFICIAL), OUT_SQL, OUT_JSON))


if __name__ == '__main__':
    main()
