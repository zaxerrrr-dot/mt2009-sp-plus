#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_globalmode_2x.py [--items items.txt]

MT2009_PLUS_237_GLOBAL_MODE_V1 - the 2.x line's M2_BONUS_MODE=global (the owner, 22 October 2026: "the whole global
setting in env - elements, refining, upgrade items, monster values, everything behind the global setting"). On the
Yohara line refining (MT2009_PLUS_REFINE_GLOBAL_V1) and the monsters' values (MT2009_PLUS_MOBY_GLOBAL_V1) are always
on; here they sit behind the same switch as the bonuses and the elements, and switch back exactly: mt2009 keeps the
world as 2.36 had it. This script renders the 2.x files from the Yohara line's data (copied unchanged):

  tools/refineglobal/ulepszanie_global.json (+ gen_refineglobal.py's load(): the owner's upgrade sheet)
      -> linux-port/docker/mariadb/playerbot/refine_global_2x.sql
         global mode only (apply.sh): refine_proto 40000.. (the sheet's recipes: Yang, chance, materials) and the
         table world.item_proto_refine_global (vnum -> the sheet's next item and recipe) for every item we have whose
         next item is the sheet's (or none, for a "+9 -> next item" step), whose result and every material exist.
         apply.sh writes it into item_proto and keeps the mt2009 values in world.item_proto_refine_mt2009.
         Left out: Seon-Pyeong's steps (gen_refineglobal.py ELITE, ids 39900-39903) - the 2.x engine has no
         IsEliteRefine (server-patches/seonpyeong is Yohara's), so the Blacksmith would make them.
  tools/globalmode/moby_global.yohara.sql (the Yohara line's mariadb/playerbot/moby_global.sql, gen_moby_global.py: guarded
  UPDATEs of world.mob_proto - a column changes only while it holds the value the clean world has)
      -> moby_global_2x.sql      every UPDATE preceded by a note of (vnum, column) in world.mob_proto_global_saved
                                 when the guard holds (the column is about to change)
      -> moby_global_mt2009.sql  back: every noted column that still holds the global value gets the clean world's
                                 value again; the notes are cleared. An operator's own value is never touched.
  linux-port/docker/game/moby_global/mob_drop_item.moby_global.txt (the sheet's drops our monsters lack)
      -> linux-port/docker/game/moby_global/mob_drop_item.moby_global.2x.txt
         without the items the 2.x world does not have (--items: one vnum a line, SELECT vnum FROM world.item_proto
         of a 2.x world; without it the file is copied as it is) - one unknown item stops every core at boot.

Example: python3 tools/globalmode/gen_globalmode_2x.py --items items.txt
Idempotent; rerun after a new copy of the Yohara data.
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
PB = os.path.join(REPO, 'linux-port', 'docker', 'mariadb', 'playerbot')
GAME = os.path.join(REPO, 'linux-port', 'docker', 'game', 'moby_global')
sys.path.insert(0, os.path.join(REPO, 'tools', 'refineglobal'))
import gen_refineglobal as R  # noqa: E402

M = 'MT2009_PLUS_237_GLOBAL_MODE_V1'
REFINE_OUT = os.path.join(PB, 'refine_global_2x.sql')
MOBY_IN = os.path.join(HERE, 'moby_global.yohara.sql')  # the Yohara line's linux-port/docker/mariadb/playerbot/moby_global.sql, as it is
MOBY_FWD = os.path.join(PB, 'moby_global_2x.sql')
MOBY_BACK = os.path.join(PB, 'moby_global_mt2009.sql')
DROP_IN = os.path.join(GAME, 'mob_drop_item.moby_global.txt')
DROP_OUT = os.path.join(GAME, 'mob_drop_item.moby_global.2x.txt')


def refine():
    recipes, steps, nochance = R.load()
    elite = [s for s in steps if R.ELITE_ID0 <= s['rid'] <= R.ELITE_ID_MAX]
    steps = [s for s in steps if not R.ELITE_ID0 <= s['rid'] <= R.ELITE_ID_MAX]
    rows = R.recipe_rows(recipes)
    L = ['-- %s: refining as on the global server (M2_BONUS_MODE=global only). GENERATED by' % M,
         '-- tools/globalmode/gen_globalmode_2x.py from tools/refineglobal/ulepszanie_global.json (the owner\'s upgrade sheet,',
         '-- read 16.10.2026; the Yohara line\'s MT2009_PLUS_REFINE_GLOBAL_V1) - do not edit, rerun it.',
         '-- %d steps with a chance, %d recipes (refine_proto %d-%d), %d steps without a chance and %d Seon-Pyeong steps'
         % (len(steps), len(recipes), R.ID0, R.ID0 + len(recipes) - 1, nochance, len(elite)),
         '-- (ids %d-%d on Yohara: the 2.x engine has no IsEliteRefine) left out. Fills world.item_proto_refine_global'
         % (R.ELITE_ID0, R.ELITE_ID_MAX),
         '-- (vnum -> the global next item and recipe): an item whose next item is the sheet\'s (or none, for a "+9 -> next',
         '-- item" step), whose result and every material exist. apply.sh writes it into item_proto (and keeps the mt2009',
         '-- values in world.item_proto_refine_mt2009). Idempotent.',
         'SET NAMES utf8mb4;',
         'USE world;',
         'INSERT INTO world.refine_proto (id,vnum0,count0,vnum1,count1,vnum2,count2,vnum3,count3,vnum4,count4,cost,'
         'src_vnum,result_vnum,prob) VALUES',
         ',\n'.join('(' + ','.join(str(x) for x in r) + ')' for r in rows),
         'ON DUPLICATE KEY UPDATE vnum0=VALUES(vnum0), count0=VALUES(count0), vnum1=VALUES(vnum1), count1=VALUES(count1),'
         ' vnum2=VALUES(vnum2), count2=VALUES(count2), vnum3=VALUES(vnum3), count3=VALUES(count3), vnum4=VALUES(vnum4),'
         ' count4=VALUES(count4), cost=VALUES(cost), src_vnum=0, result_vnum=0, prob=VALUES(prob);',
         'DROP TEMPORARY TABLE IF EXISTS tmp_refine_global;',
         'CREATE TEMPORARY TABLE tmp_refine_global (src INT UNSIGNED NOT NULL PRIMARY KEY, res INT UNSIGNED NOT NULL,'
         ' rid INT UNSIGNED NOT NULL, tr TINYINT NOT NULL);',
         'INSERT INTO tmp_refine_global (src,res,rid,tr) VALUES',
         ',\n'.join('(%d,%d,%d,%d)' % (s['src'], s['res'], s['rid'], s['tr']) for s in steps) + ';',
         '-- a step whose material is not in our item_proto stays as it is',
         'DROP TEMPORARY TABLE IF EXISTS tmp_refine_global_mat;',
         'CREATE TEMPORARY TABLE tmp_refine_global_mat (rid INT UNSIGNED NOT NULL, vnum INT UNSIGNED NOT NULL,'
         ' PRIMARY KEY (rid, vnum));',
         'INSERT IGNORE INTO tmp_refine_global_mat (rid,vnum) VALUES',
         ',\n'.join('(%d,%d)' % (r[0], v) for r in rows for v in r[1:11:2] if v) + ';',
         'DELETE s FROM tmp_refine_global s JOIN tmp_refine_global_mat m ON m.rid = s.rid'
         ' LEFT JOIN world.item_proto p ON p.vnum = m.vnum WHERE p.vnum IS NULL;',
         'CREATE TABLE IF NOT EXISTS world.item_proto_refine_global (vnum INT UNSIGNED NOT NULL PRIMARY KEY,'
         ' refined_vnum INT UNSIGNED NOT NULL, refine_set INT UNSIGNED NOT NULL) ENGINE=InnoDB;',
         'START TRANSACTION;',
         'DELETE FROM world.item_proto_refine_global;',
         'INSERT INTO world.item_proto_refine_global (vnum, refined_vnum, refine_set)'
         ' SELECT i.vnum, s.res, s.rid FROM world.item_proto i JOIN tmp_refine_global s ON s.src = i.vnum'
         ' JOIN world.item_proto r ON r.vnum = s.res WHERE i.refined_vnum = s.res OR (s.tr = 1 AND i.refined_vnum = 0);',
         'COMMIT;',
         'DROP TEMPORARY TABLE tmp_refine_global_mat;',
         'DROP TEMPORARY TABLE tmp_refine_global;']
    with open(REFINE_OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(L) + '\n')
    return 'refine: %d steps, %d recipes, %d Seon-Pyeong steps left out' % (len(steps), len(recipes), len(elite))


NUM_RE = re.compile(r'^UPDATE world\.mob_proto SET `(\w+)` = (-?\d+) WHERE vnum = (\d+) AND `\1` = (-?\d+);$')
SET_RE = re.compile(r"^UPDATE world\.mob_proto SET `(\w+)` = '([^']*)' WHERE vnum = (\d+) AND `\1` = '([^']*)';$")
RACE_RE = re.compile(r'^UPDATE world\.mob_proto SET `setRaceFlag` = \(`setRaceFlag` \+ 0\) \| (\d+) WHERE vnum = (\d+) AND '
                     r'\(`setRaceFlag` \+ 0\) & 2047 = 0;$')
SAVED = 'world.mob_proto_global_saved'


def moby():
    fwd = ['-- %s: the monsters as on the global server (M2_BONUS_MODE=global only). GENERATED by' % M,
           '-- tools/globalmode/gen_globalmode_2x.py from moby_global.sql (the Yohara line\'s MT2009_PLUS_MOBY_GLOBAL_V1,',
           '-- the owner\'s sheet of 20 October 2026) - do not edit, rerun it. Every guarded UPDATE of moby_global.sql, each',
           '-- noted first in %s while its guard holds (the column is the clean world\'s and is about to' % SAVED,
           '-- change), so moby_global_mt2009.sql can put back exactly these columns. Every start in global mode; idempotent.',
           'SET NAMES utf8mb4;',
           'CREATE TABLE IF NOT EXISTS %s (vnum INT UNSIGNED NOT NULL, col VARCHAR(32) NOT NULL,' % SAVED,
           ' PRIMARY KEY (vnum, col)) ENGINE=InnoDB;']
    back = ['-- %s: back from M2_BONUS_MODE=global (apply.sh, mt2009 mode, while %s has rows). GENERATED' % (M, SAVED),
            '-- by tools/globalmode/gen_globalmode_2x.py - do not edit. A column global mode changed (noted) that still holds',
            '-- the global value gets the clean world\'s value back; an operator\'s own value stays. Then the notes go.',
            'SET NAMES utf8mb4;',
            'CREATE TABLE IF NOT EXISTS %s (vnum INT UNSIGNED NOT NULL, col VARCHAR(32) NOT NULL,' % SAVED,
            ' PRIMARY KEY (vnum, col)) ENGINE=InnoDB;']
    n = 0
    for line in open(MOBY_IN, encoding='utf-8'):
        line = line.rstrip('\n')
        if not line.startswith('UPDATE'):
            continue
        m = NUM_RE.match(line)
        if m:
            c, new, v, old = m.groups()
            guard, back_guard, setback = '`%s` = %s' % (c, old), '`%s` = %s' % (c, new), '`%s` = %s' % (c, old)
            key = c
        else:
            m = SET_RE.match(line)
            if m:
                c, new, v, old = m.groups()
                guard, back_guard, setback = "`%s` = '%s'" % (c, old), "`%s` = '%s'" % (c, new), "`%s` = '%s'" % (c, old)
                key = c
            else:
                m = RACE_RE.match(line)
                assert m, line
                bit, v = m.groups()
                guard = '(`setRaceFlag` + 0) & 2047 = 0'
                back_guard = '(`setRaceFlag` + 0) & 2047 = %s' % bit
                setback = '`setRaceFlag` = (`setRaceFlag` + 0) & ~%s' % bit
                key = 'setRaceFlag:%s' % bit
        fwd.append("INSERT IGNORE INTO %s (vnum, col) SELECT vnum, '%s' FROM world.mob_proto WHERE vnum = %s AND %s;"
                   % (SAVED, key, v, guard))
        fwd.append(line)
        al = lambda s: re.sub(r'`(\w+)`', r'm.`\1`', s)  # noqa: E731
        back.append("UPDATE world.mob_proto m JOIN %s s ON s.vnum = m.vnum AND s.col = '%s' SET %s WHERE m.vnum = %s"
                    " AND %s;" % (SAVED, key, al(setback), v, al(back_guard)))
        n += 1
    back.append('DELETE FROM %s;' % SAVED)
    for path, L in ((MOBY_FWD, fwd), (MOBY_BACK, back)):
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write('\n'.join(L) + '\n')
    return 'monsters: %d guarded UPDATEs (forward with notes, and back)' % n


def drops(items_path):
    src = open(DROP_IN, encoding='utf-8', newline='').read().replace('\r\n', '\n')
    items = None
    if items_path:
        items = set(int(x) for x in open(items_path).read().split() if x.isdigit())
    out, block, rows, k, cut, gone = [], [], 0, 0, 0, 0
    head = True
    for line in src.split('\n'):
        p = line.split('--')[0].split()
        if head and line.startswith('//'):
            out.append(line)
            continue
        if head:
            head = False
            out.append('// %s (2.x): without the items the 2.x world lacks (tools/globalmode/gen_globalmode_2x.py).' % M)
        if p and p[0] == 'Group':
            block, rows, k = [line], 0, 0
            continue
        if block:
            if p and p[0].isdigit() and len(p) >= 4:
                if items is not None and int(p[1]) not in items:
                    cut += 1
                    continue
                k += 1
                rows += 1
                line = re.sub(r'^(\s*)\d+', lambda mm: mm.group(1) + str(k), line, count=1)
            block.append(line)
            if p and p[0] == '}':
                if rows:
                    out.extend(block)
                else:
                    gone += 1
                block = []
            continue
        out.append(line)
    while out and out[-1] == '':
        out.pop()
    with open(DROP_OUT, 'w', encoding='utf-8', newline='\r\n') as f:
        f.write('\n'.join(out) + '\n')
    return 'drops: %d row(s) of items the 2.x world lacks left out, %d group(s) left empty%s' % (
        cut, gone, '' if items is not None else ' (no --items: nothing checked)')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--items', help='one item vnum a line (SELECT vnum FROM world.item_proto of a 2.x world)')
    a = ap.parse_args()
    for r in (refine(), moby(), drops(a.items)):
        print(r)


if __name__ == '__main__':
    main()
